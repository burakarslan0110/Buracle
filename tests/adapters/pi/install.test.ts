import { describe, expect, test } from 'bun:test'
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { devContext } from '../../../src/adapters/omp/dev-build'
import { adapter, uninstallPlan } from '../../../src/adapters/pi/index'
import { buildPi, EXTENSION_PATH, piMcpEntry, piMcpServers } from '../../../src/adapters/pi/build'
import { mcpFindings } from '../../../src/adapters/pi/doctor'
import { piExtensionFile, piMcpFile } from '../../../src/adapters/pi/install'
import type { AdapterContext } from '../../../src/adapters/registry'
import { harnessProfile } from '../../../src/core/harness/index'
import * as paths from '../../../src/engine/paths'
import { readLedger, applyPlans } from '../../../src/engine/txn'
import { fakeExe, narrowPath } from '../../helpers/fake-exe'
import { withEnv, withSandbox } from '../../helpers/sandbox'

const REPO = paths.repoRoot()
const ctx = (): AdapterContext => devContext(REPO)

describe('the Pi build', () => {
  test('one extension, the MCP entries and a README, in a stable order', async () => {
    const files = await buildPi(ctx())
    expect(files.map(f => f.path)).toEqual([EXTENSION_PATH, 'mcp.json', 'README.md'])
    expect(files[0]?.content).toStartWith('// Buracle extension for Pi. GENERATED by `buracle build`')
    expect(files[0]?.content).toContain('agent_before_settle')
  })

  test('mcp.json holds exactly the servers canonical/mcp.yaml gives Pi, behind the buracle shim, timeouts in seconds', () => {
    const c = ctx()
    const servers = piMcpServers(c.canonical)
    expect(Object.keys(servers)).toEqual(Object.keys(c.canonical.mcp.servers).sort().filter(id => c.canonical.mcp.servers[id]?.harnesses.includes('pi')))
    const memory = servers['buracle-memory'] as { command: string, args: string[] }
    expect(memory.command).toBe('/bin/sh')
    expect(memory.args.slice(-2)).toEqual(['mcp', 'memory'])
    const timed = Object.entries(c.canonical.mcp.servers).find(([, s]) => s.tool_timeout_sec !== undefined)
    if (timed !== undefined) expect(piMcpEntry(timed[0], timed[1])['timeout']).toBe(timed[1].tool_timeout_sec)
  })

  test('every entry that starts through the buracle launcher says it runs for Pi (both Pi and omp send the client name `pi`)', () => {
    const servers = piMcpServers(ctx().canonical)
    for (const [id, e] of Object.entries(servers)) {
      const viaLauncher = e['command'] === '/bin/sh'
      expect({ id, marker: (e['env'] as Record<string, string> | undefined)?.['BURACLE_HARNESS'] }).toEqual({ id, marker: viaLauncher ? 'pi' : undefined })
    }
    expect(Object.values(servers).some(e => e['command'] === '/bin/sh')).toBe(true)
  })

  test('the bundle runs on Node: no Bun-only module paths, and the Bun stand-in comes first', async () => {
    const text = (await buildPi(ctx()))[0]?.content ?? ''
    expect(text).not.toMatch(/import\.meta\.dir\b(?!name)/)
    expect(text).not.toContain('import.meta.require;')
    expect(text).toContain('import.meta.dirname')
    expect(text.indexOf('TOML is not available in this runtime')).toBeGreaterThan(0)
    expect(text.indexOf('globalThis')).toBeLessThan(text.indexOf('agent_before_settle'))
  })

  test('a server that is off for Pi stays listed, disabled', () => {
    const c = ctx()
    const id = Object.keys(piMcpServers(c.canonical))[0] as string
    expect(piMcpServers(c.canonical, [id])[id]?.['enabled']).toBe(false)
    expect(piMcpServers(c.canonical)[id]?.['enabled']).toBeUndefined()
  })

  test('the profile no longer waits for an adapter, and the generated tree is what `build` writes', async () => {
    expect(harnessProfile('pi').adapterPending).toBeUndefined()
    for (const f of await buildPi(ctx())) expect(readFileSync(join(REPO, 'harness', 'pi', f.path), 'utf8')).toBe(f.content)
  })
})

describe('the Pi install', () => {
  const dir = () => paths.piAgentDir()

  test('the plan is the extension file and a key-by-key merge into mcp.json', () => withSandbox(async () => {
    const plan = await adapter.installPlan(ctx())
    expect(plan.harness).toBe('pi')
    expect(plan.ops.map(o => o.kind)).toEqual(['file', 'json-merge'])
  }))

  test('install writes into the agent folder, keeps what the user has, and uninstall removes only what it wrote', () => withSandbox(async () => {
    mkdirSync(dir(), { recursive: true })
    const mcpFile = piMcpFile(dir())
    writeFileSync(mcpFile, JSON.stringify({ mcpServers: { mine: { command: 'mine' } }, other: 1 }, null, 2))
    const c = ctx()
    await applyPlans([await adapter.installPlan(c)])
    expect(readFileSync(piExtensionFile(dir()), 'utf8')).toBe(readFileSync(join(REPO, 'harness', 'pi', EXTENSION_PATH), 'utf8'))
    const doc = JSON.parse(readFileSync(mcpFile, 'utf8')) as { mcpServers: Record<string, unknown>, other: number }
    expect(doc.other).toBe(1)
    expect(doc.mcpServers['mine']).toEqual({ command: 'mine' })
    expect(Object.keys(doc.mcpServers).sort()).toEqual(['mine', ...Object.keys(piMcpServers(c.canonical))].sort())
    const owned = Object.values(await readLedger()).filter(e => e.owner === 'pi')
    expect(owned.length).toBe(1 + Object.keys(piMcpServers(c.canonical)).length)
    for (const e of owned) expect(e.path.startsWith(dir())).toBe(true)

    await applyPlans([await uninstallPlan(c)])
    expect(existsSync(piExtensionFile(dir()))).toBe(false)
    expect(JSON.parse(readFileSync(mcpFile, 'utf8'))).toEqual({ mcpServers: { mine: { command: 'mine' } }, other: 1 })
    expect(Object.values(await readLedger()).filter(e => e.owner === 'pi')).toEqual([])
  }))

  test('an extension file the user changed is kept, and so is a server entry they edited', () => withSandbox(async () => {
    const c = ctx()
    await applyPlans([await adapter.installPlan(c)])
    writeFileSync(piExtensionFile(dir()), '// mine\n')
    const mcpFile = piMcpFile(dir())
    const doc = JSON.parse(readFileSync(mcpFile, 'utf8')) as { mcpServers: Record<string, Record<string, unknown>> }
    doc.mcpServers['buracle-memory'] = { command: 'my-memory' }
    writeFileSync(mcpFile, JSON.stringify(doc))
    const r = await applyPlans([await adapter.installPlan(c)])
    expect(readFileSync(piExtensionFile(dir()), 'utf8')).toBe('// mine\n')
    expect((JSON.parse(readFileSync(mcpFile, 'utf8')) as { mcpServers: Record<string, unknown> }).mcpServers['buracle-memory']).toEqual({ command: 'my-memory' })
    expect(JSON.stringify(r)).toContain('keeping')
  }))

  test('PI_CODING_AGENT_DIR moves the folder', () => withSandbox(async ({ root }) => {
    const elsewhere = join(root, 'pi-agent')
    await withEnv({ PI_CODING_AGENT_DIR: elsewhere }, async () => {
      await applyPlans([await adapter.installPlan(ctx())])
      expect(existsSync(join(elsewhere, EXTENSION_PATH))).toBe(true)
    })
  }))
})

describe('the Pi doctor', () => {
  test('a missing program is one warning; a missing extension and MCP file are findings with the fix', () => withSandbox(async ({ root }) => {
    await withEnv({ PATH: join(root, 'empty') }, async () => {
      const rows = await adapter.doctor(ctx())
      expect(rows.at(-1)).toMatchObject({ level: 'warn', check: 'pi' })
    })
    const bin = join(root, 'bin')
    fakeExe(join(bin, 'pi'), 'console.log("1.5.2")')
    await withEnv({ PATH: narrowPath(bin) }, async () => {
      const rows = await adapter.doctor(ctx())
      expect(rows.find(r => r.check === 'pi.version')).toMatchObject({ level: 'ok' })
      expect(rows.find(r => r.check === 'pi.extension')).toMatchObject({ level: 'error' })
      expect(rows.find(r => r.check === 'pi.mcp')?.detail).toContain('missing')
      await applyPlans([await adapter.installPlan(ctx())])
      // The entries start through the shim in $BURACLE_HOME/bin.
      mkdirSync(join(paths.buracleHome(), 'bin'), { recursive: true })
      writeFileSync(join(paths.buracleHome(), 'bin', 'buracle'), '#!/bin/sh\nexit 0\n')
      chmodSync(join(paths.buracleHome(), 'bin', 'buracle'), 0o755)
      const after = await adapter.doctor(ctx())
      expect(after.find(r => r.check === 'pi.extension')).toMatchObject({ level: 'ok' })
      expect(after.find(r => r.check === 'pi.mcp')).toMatchObject({ level: 'ok' })
    })
    fakeExe(join(bin, 'pi'), 'console.log("1.0.0")')
    await withEnv({ PATH: narrowPath(bin) }, async () => {
      expect((await adapter.doctor(ctx())).find(r => r.check === 'pi.version')).toMatchObject({ level: 'error' })
    })
  }))

  test('mcpFindings reports a missing server and a command that cannot start', () => {
    const text = JSON.stringify({ mcpServers: { a: { command: '/nonexistent/x' }, b: { command: '/bin/sh', args: ['-c', 'true'] } } })
    const rows = mcpFindings(text, ['a', 'b', 'c'], '/f/mcp.json', process.env)
    expect(rows.map(r => `${r.level}:${r.check}`)).toEqual(['warn:pi.mcp', 'error:pi.mcp'])
    expect(rows[0]?.detail).toContain('c')
    expect(mcpFindings(undefined, [], '/f/mcp.json', process.env)[0]?.level).toBe('warn')
    expect(mcpFindings('{', [], '/f/mcp.json', process.env)[0]?.level).toBe('error')
  })
})
