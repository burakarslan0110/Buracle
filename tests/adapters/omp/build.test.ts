describe('omp dev-build helper', () => {
  test('writeTree replaces the tree (stale files and empty dirs go); diffTree reports drift', () => withSandbox(async sb => {
    const dir = join(sb.root, 'harness-omp')
    mkdirSync(join(dir, 'old', 'deep'), { recursive: true })
    writeFileSync(join(dir, 'old', 'deep', 'gone.md'), 'x')
    const files = [{ path: 'a.md', content: 'A\n' }, { path: 'rules/b.md', content: 'B\n' }]
    expect(diffTree(dir, files).sort()).toEqual(['missing a.md', 'missing rules/b.md', 'stale old/deep/gone.md'])
    writeTree(dir, files)
    expect(listFiles(dir)).toEqual(['a.md', 'rules/b.md'])
    expect(existsSync(join(dir, 'old'))).toBe(false)
    if (KEEPS_MODES) expect(statSync(join(dir, 'a.md')).mode & 0o777).toBe(0o644)
    expect(diffTree(dir, files)).toEqual([])
    writeFileSync(join(dir, 'a.md'), 'changed\n')
    expect(diffTree(dir, files)).toEqual(['changed a.md'])
  }))
})
