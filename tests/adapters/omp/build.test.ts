  test.skipIf(process.platform === 'win32')('I8 / SEC-10: the buracle-memory command reaches the shim under a custom BURACLE_HOME, whether or not omp pre-expands it (POSIX; on Windows the agent dir\'s mcp.json runs the servers)', () => withSandbox(async ({ root, home }) => {
    const entry = JSON.parse(byPath(await buildOmp(fixtureCtx()))['.mcp.json'] as string).mcpServers['buracle-memory'] as { command: string, args: string[] }
    const ompExpand = (s: string, env: Record<string, string | undefined>) => s.replace(/\$\{([^}:]+)(?::-([^}]*))?\}/g, (_m, v: string, d?: string) => {
      const e = env[v]
      if (e !== undefined && (d === undefined || e !== '')) return e
      return d !== undefined ? d : `\${${v}}`
    })
    const shim = (dir: string, tag: string) => {
      mkdirSync(join(dir, 'bin'), { recursive: true })
      writeFileSync(join(dir, 'bin', 'buracle'), `#!/bin/sh\necho "${tag} $*"\n`)
      Bun.spawnSync(['chmod', '755', join(dir, 'bin', 'buracle')])
    }
    const custom = join(root, 'custom-buracle')
    shim(custom, 'custom')
    shim(join(home, '.buracle'), 'default')
    for (const pre of [true, false]) {
      for (const [bh, want] of [[custom, 'custom mcp memory'], [undefined, 'default mcp memory']] as const) {
        const env: Record<string, string | undefined> = { HOME: home, PATH: '/usr/bin:/bin', ...(bh !== undefined ? { BURACLE_HOME: bh } : {}) }
        const argv = [entry.command, ...entry.args].map(a => (pre ? ompExpand(a, env) : a))
        const out = Bun.spawnSync(argv, { env: env as Record<string, string> }).stdout.toString().trim()
        expect({ pre, bh, out }).toEqual({ pre, bh, out: want })
      }
    }
  }))

