describe('omp build: rendering helpers', () => {
  test('harness blocks: omp kept (markers dropped), others removed, multi-harness lists honored', () => {
    expect(filterHarnessBlocks('a\n<!-- harness:claude -->\nC\n<!-- /harness -->\nb\n<!-- harness:codex, omp -->\nX\n<!-- /harness -->\nc\n')).toBe('a\nb\nX\nc\n')
  })

  test('placeholders: prose vs code spans vs fences, escapes and unknown names', () => {
    expect(expandPlaceholders('Use {{todo}} and {{skill:memory}}; `{{skill:plan-build}} go`; \\{{ask_user}}; {{nope}}'))
      .toBe('Use the `todo` tool and `/skill:memory`; `/skill:plan-build go`; {{ask_user}}; {{nope}}')
    expect(expandPlaceholders('```\n{{spawn_agent}} {{agent:x}}\n```\n{{spawn_agent}}')).toBe('```\ntask x\n```\nthe `task` tool')
    expect(renderForOmp('a\n\n\n\nb')).toBe('a\n\nb')
  })

  test('frontmatter: quoted scalars, block lists, empty lists, skipped undefined', () => {
    expect(frontmatter([['a', 'x: "y"'], ['b', true], ['c', ['*.ts']], ['d', []], ['e', undefined]])).toBe('---\na: "x: \\"y\\""\nb: true\nc:\n  - "*.ts"\nd: []\n---\n')
  })

  test('isOmpFileGlob mirrors omp: globs with a slash or *.ext, never regex-looking tokens', () => {
    for (const g of ['**/*.py', '*.rs', '**/api/**', '**/requirements*.txt', '**/playwright.config.*', 'src/**/*.{ts,tsx}']) expect(isOmpFileGlob(g)).toBe(true)
    for (const g of ['Dockerfile', 'foo.ts', 'a|b', '(x)/*', '^src/', '']) expect(isOmpFileGlob(g)).toBe(false)
  })

  test('every canonical path-rule glob is expressed: omp glob shorthand, else explicit edit/write scopes', () => {
    const canonical = devContext().canonical
    for (const rule of canonical.rules.filter(r => r.scope === 'paths')) {
      const out = renderRule(rule).content
      const globs = (rule.frontmatter['paths'] as string[]) ?? []
      expect(globs.length).toBeGreaterThan(0)
      for (const g of globs) {
        if (isOmpFileGlob(g)) expect(out).toContain(`  - ${JSON.stringify(g)}\n`)
        else expect(out).toContain(`  - ${JSON.stringify(`tool:edit(${g})`)}\n`)
      }
    }
  })

  test('the shipped path rules (mobile, dotnet and blazor included) use omp glob conditions only', () => {
    const rules = devContext().canonical.rules.filter(r => r.scope === 'paths')
    expect(rules.map(r => r.id)).toEqual(expect.arrayContaining(['blazor', 'dotnet', 'mobile']))
    for (const rule of rules) {
      const notGlobs = ((rule.frontmatter['paths'] as string[]) ?? []).filter(g => !isOmpFileGlob(g))
      expect({ rule: rule.id, notGlobs }).toEqual({ rule: rule.id, notGlobs: [] })
    }
  })

  test('a rule title keeps a # inside a word (C#); only a closing # sequence after a space is dropped', () => {
    const dotnet = devContext().canonical.rules.find(r => r.id === 'dotnet')
    expect(dotnet).toBeDefined()
    expect(renderRule(dotnet as NonNullable<typeof dotnet>).content).toContain('description: "Buracle path rule: .NET and C# (injected when editing or writing matching files)"\n')
    expect(firstHeading('# .NET and C#\n')).toBe('.NET and C#')
    expect(firstHeading('# Python ##\n')).toBe('Python')
    expect(firstHeading('# Go  \n\n- gofmt')).toBe('Go')
  })
})

describe('omp build: determinism and machine independence (live canonical)', () => {
  test('two builds are byte-identical and contain no absolute user paths', async () => {
    const ctx = devContext()
    const a = await buildOmp(ctx)
    const b = await buildOmp(devContext())
    expect(b).toEqual(a)
    const forbidden = forbiddenPaths()
    for (const f of a) for (const p of forbidden) expect({ file: f.path, has: f.content.includes(p) }).toEqual({ file: f.path, has: false })
    expect(a.find(f => f.path === 'extensions/buracle.js')?.content.startsWith(BUNDLE_BANNER)).toBe(true)
  })

  test('the bundle does not depend on the working directory of the build', async () => {
    const dir = mkdtempSync(join(realpathSync(tmpdir()), 'buracle-omp-cwd-'))
    try {
      const script = join(dir, 'bundle-hash.ts')
      writeFileSync(script, [
        `import { buildOmp } from ${JSON.stringify(join(REPO, 'src/adapters/omp/build.ts'))}`,
        `import { devContext } from ${JSON.stringify(join(REPO, 'src/adapters/omp/dev-build.ts'))}`,
        'const files = await buildOmp(devContext())',
        'process.stdout.write(JSON.stringify(files))',
      ].join('\n'))
      const proc = Bun.spawnSync([process.execPath, script], { cwd: dir, stdout: 'pipe', stderr: 'pipe', env: process.env })
      expect(proc.stderr.toString()).toBe('')
      const there = JSON.parse(proc.stdout.toString()) as BuildFile[]
      const here = await buildOmp(devContext())
      expect(there.map(f => [f.path, f.mode])).toEqual(here.map(f => [f.path, f.mode]))
      for (const [i, f] of here.entries()) expect({ file: f.path, diff: firstLineDiff(f.content, there[i]?.content ?? '') }).toEqual({ file: f.path, diff: undefined })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  }, 30_000)

  test('module comments are rewritten relative to the repo root', () => {
    expect(repoRelativeModuleComments('// ../../w/repo/src/a.ts\ncode // ../../w/repo/x\n', '/w/repo', '/a/b')).toBe('// src/a.ts\ncode // ../../w/repo/x\n')
    expect(repoRelativeModuleComments('// ../src/a.ts\n', '/w/repo', '/w/repo/tests')).toBe('// src/a.ts\n')
    expect(repoRelativeModuleComments('// src/a.ts\n', '/w/repo', '/w/repo')).toBe('// src/a.ts\n')
  })

  test('module comments across Windows drives (repo on D:, cwd on C:) carry the absolute path, with either separator; both become repo-relative', () => {
    const text = '// D:/a/Buracle/src/a.ts\n// D:\\a\\Buracle\\src\\b.ts\ncode // D:/a/Buracle/x\n// d:/other/src/c.ts\n// d:/a/Buracle/src/e.ts\n// ../../../D:/a/Buracle/node_modules/y.js\n'
    expect(repoRelativeModuleComments(text, 'D:\\a\\Buracle', 'C:\\Users\\me')).toBe('// src/a.ts\n// src/b.ts\ncode // D:/a/Buracle/x\n// d:/other/src/c.ts\n// src/e.ts\n// node_modules/y.js\n')
  })
})

