describe('omp build: canonical/hooks.yaml matches what the extension subscribes to', () => {
  test('every omp event the hook matrix names (also extra events) is one the built extension registers', () => withSandbox(async sb => {
    const real = loadCanonicalSync(join(REPO, 'canonical'))
    const code = await bundleExtension(REPO, ompGeneratedData(real, '0.1.0'))
    const file = join(sb.root, 'buracle-matrix.js')
    writeFileSync(file, code)
    const mod = await import(file) as { default: (pi: unknown) => void }
    const fp = fakePi()
    mod.default(fp.pi)
    const registered = new Set(fp.handlers.keys())
    const named: string[] = []
    for (const h of real.hooks.hooks) {
      const b = h.bindings.omp as { event?: string, also?: Array<{ event: string }> } | undefined
      if (b?.event === undefined) continue
      named.push(`${h.id}:${b.event}`, ...(b.also ?? []).map(a => `${h.id}:${a.event}`))
    }
    expect(named.length).toBeGreaterThan(10)
    expect(named.filter(n => !registered.has(n.slice(n.indexOf(':') + 1)))).toEqual([])
    expect(registered.has('session_before_compact')).toBe(false)
  }))
})

