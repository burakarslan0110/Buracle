function byPath(files: BuildFile[]): Record<string, string> {
  return Object.fromEntries(files.map(f => [f.path, f.content]))
}

function forbiddenPaths(): string[] {
  const out = new Set<string>([homedir(), REPO, realpathSync(REPO), realpathSync(tmpdir()), `/Users/${userInfo().username}`, `/home/${userInfo().username}`])
  if (process.env['HOME']) out.add(process.env['HOME'])
  return [...out].filter(p => p.length > 4)
}

