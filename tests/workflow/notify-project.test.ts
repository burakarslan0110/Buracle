    const clean = await projectCheck(ctxAt(repo))
    expect([clean.code, clean.data['ok']]).toEqual([0, true])
    expect(clean.lines).toContain('In step: nothing to fix.')

    write(join(repo, '.claude', 'rules', 'nested', 'web.md'), '---\npaths: ["src/**/*.tsx"]\n---\n')
