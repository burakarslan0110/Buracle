function sandbox(fn: (root: string, buracleHome: string) => Promise<void>): Promise<void> {
  return withSandbox(({ root, buracleHome }) => withEnv({ BURACLE_NO_MEMORY: '1' }, () => fn(root, buracleHome)))
}

describe('notify', () => {
  test('records every type in notifications.jsonl; BURACLE_NO_NOTIFY skips the macOS banner', () => sandbox(async (root, buracleHome) => {
    expect(NOTIFY_TYPES).toEqual(['info', 'plan_approval', 'prd_approval', 'attention_needed', 'verification_complete'])
    for (const t of NOTIFY_TYPES) {
      const r = await notify(t, `Title ${t}`, 'Message: "quotes" and \\ backslashes', { plan: 'docs/plans/x.md' }, ctxAt(root), SESSION)
      expect(r.code).toBe(0)
      expect(r.data).toMatchObject({ ok: true, type: t, delivery: { macos: 'skipped' } })
    }
    expect(notificationsFile()).toBe(join(buracleHome, 'state', 'notifications.jsonl'))
    const lines = readFileSync(notificationsFile(), 'utf8').trim().split('\n').map(l => JSON.parse(l) as Record<string, unknown>)
    expect(lines.length).toBe(5)
    expect(lines[1]).toMatchObject({ type: 'plan_approval', title: 'Title plan_approval', plan: join(root, 'docs/plans/x.md'), harness: 'claude', session: SESSION.sessionId })
    for (const l of lines) expect(l['delivery']).toEqual({ macos: 'skipped' })
  }))

  test('notifications.jsonl stays bounded: past NOTIFICATIONS_MAX_BYTES only the newest NOTIFICATIONS_KEEP records stay', () => sandbox(async root => {
    const old = JSON.stringify({ ts: '2026-01-01T00:00:00.000Z', type: 'info', title: 'old', message: 'x'.repeat(500) })
    mkdirSync(join(notificationsFile(), '..'), { recursive: true })
    const count = Math.ceil(NOTIFICATIONS_MAX_BYTES / old.length) + 10
    writeFileSync(notificationsFile(), `${old}\n`.repeat(count), { mode: 0o600 })
    expect((await notify('info', 'newest', 'm', {}, ctxAt(root), undefined)).code).toBe(0)
    const lines = readFileSync(notificationsFile(), 'utf8').trim().split('\n')
    expect(lines.length).toBe(NOTIFICATIONS_KEEP)
    expect(JSON.parse(lines[lines.length - 1] as string)).toMatchObject({ title: 'newest' })
    if (process.platform !== 'win32') expect(statSync(notificationsFile()).mode & 0o777).toBe(0o600)
    expect((await notify('info', 'one more', 'm', {}, ctxAt(root), undefined)).code).toBe(0)
    expect(readFileSync(notificationsFile(), 'utf8').trim().split('\n').length).toBe(NOTIFICATIONS_KEEP + 1)
  }))

  test('every record has an id; the list is newest first, marks what was read, and keeps the marks only for records still in the file', () => sandbox(async root => {
    mkdirSync(join(notificationsFile(), '..'), { recursive: true })
    const legacy = JSON.stringify({ ts: '2026-10-01T09:00:00.000Z', type: 'info', title: 'from an older Buracle', message: 'no id' })
    writeFileSync(notificationsFile(), `${legacy}\nnot json\n`, { mode: 0o600 })
    const a = await notify('plan_approval', 'Plan ready', 'Ready for your review', { plan: 'docs/plans/p.md' }, ctxAt(root, Date.UTC(2026, 9, 8, 12)), SESSION)
    const b = await notify('attention_needed', 'Input needed', '2 questions', {}, ctxAt(root, Date.UTC(2026, 9, 8, 13)), SESSION)
    const ida = a.data['id'] as string
    const idb = b.data['id'] as string
    expect(ida).toMatch(/^n[0-9a-z]+-[0-9a-f]{6}$/)
    expect(ida).not.toBe(idb)
    const list = readNotifications()
    expect(list.map(e => e.title)).toEqual(['Input needed', 'Plan ready', 'from an older Buracle'])
    expect(list[1]).toMatchObject({ id: ida, type: 'plan_approval', plan: join(root, 'docs/plans/p.md'), harness: 'claude', session: SESSION.sessionId, read: false })
    const legacyId = list[2]?.id as string
    expect(legacyId).toMatch(/^l-[0-9a-f]{12}$/)
    expect(readNotifications()[2]?.id).toBe(legacyId)
    expect(markNotificationsRead([ida, 'n-gone'])).toEqual({ marked: 1, unread: 2, unknown: ['n-gone'] })
    expect(readNotifications().map(e => e.read)).toEqual([false, true, false])
    expect(markNotificationsRead('all')).toEqual({ marked: 2, unread: 0, unknown: [] })
    writeFileSync(notificationsFile(), readFileSync(notificationsFile(), 'utf8').split('\n').filter(l => !l.includes('older Buracle')).join('\n'))
    markNotificationsRead([])
    expect(JSON.parse(readFileSync(notificationsReadFile(), 'utf8'))).toEqual({ v: 1, read: [idb, ida] })
    if (process.platform !== 'win32') expect(statSync(notificationsReadFile()).mode & 0o777).toBe(0o600)
  }))

  test('buracle notify list and read: the unread ones, a limit, JSON, and usage errors', () => sandbox(async root => {
    for (let i = 0; i < 3; i++) await notify('info', `Note ${i}`, `m${i}`, {}, ctxAt(root, Date.UTC(2026, 9, 8, 12, i)), undefined)
    const ctx = ctxAt(root)
    const listed = memIO(true)
    expect(await runNotify(['list', '--limit', '2'], listed, ctx)).toBe(0)
    const j = listed.json<{ unread: number, total: number, notifications: Array<{ id: string, title: string }> }>()
    expect(j.unread).toBe(3)
    expect(j.total).toBe(3)
    expect(j.notifications.map(n => n.title)).toEqual(['Note 2', 'Note 1'])
    const read = memIO()
    expect(await runNotify(['read', j.notifications[0]?.id as string], read, ctx)).toBe(0)
    expect(read.out()).toBe('Marked 1 read; 2 unread.\n')
    const unread = memIO()
    expect(await runNotify(['list', '--unread'], unread, ctx)).toBe(0)
    expect(unread.out()).not.toContain('Note 2')
    expect(unread.out()).toMatch(/^\* \d{4}-\d{2}-\d{2} \d{2}:\d{2} {2}info +Note 1 · m1 {2}\[n[0-9a-z]+-[0-9a-f]{6}\]$/m)
    expect(unread.out()).toContain('2 unread of 3')
    expect(await runNotify(['read', '--all'], memIO(), ctx)).toBe(0)
    const none = memIO()
    expect(await runNotify(['list', '--unread'], none, ctx)).toBe(0)
    expect(none.out()).toBe('No unread notifications.\n')
    expect(await runNotify(['read'], memIO(), ctx)).toBe(1)
    expect(await runNotify(['read', 'n-nope'], memIO(), ctx)).toBe(1)
    expect(await runNotify(['read', 'BAD ID'], memIO(), ctx)).toBe(1)
    expect(await runNotify(['list', '--limit', '0'], memIO(), ctx)).toBe(1)
    expect(await runNotify(['list', '--all'], memIO(), ctx)).toBe(1)
  }))

  test('usage errors exit 1 and record nothing', () => sandbox(async root => {
    expect((await notify('urgent', 't', 'm', {}, ctxAt(root), undefined)).code).toBe(1)
    expect((await notify('info', '', 'm', {}, ctxAt(root), undefined)).code).toBe(1)
    expect((await notify('info', 't', undefined, {}, ctxAt(root), undefined)).code).toBe(1)
    expect(existsSync(notificationsFile())).toBe(false)
  }))
})

