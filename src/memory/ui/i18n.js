export const lang = 'en'
const dict = EN
const nf = new Intl.NumberFormat(lang)
const pr = new Intl.PluralRules(lang)
const lf = typeof Intl.ListFormat === 'function' ? new Intl.ListFormat(lang, { style: 'long', type: 'conjunction' }) : null
const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto', style: 'short' })
const df = new Intl.DateTimeFormat(lang, { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })

export function t(key, vars) {
  let s = dict[key] ?? key
  if (vars !== undefined) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m))
  return s
}

export function num(n) { return nf.format(n) }

export function count(what, n) {
  return t(`count.${what}.${pr.select(n) === 'one' ? 'one' : 'other'}`, { n: num(n) })
}

export function listJoin(items) {
  return lf !== null ? lf.format(items) : items.join(', ')
}

export function relTime(iso, nowMs = Date.now()) {
  const ms = Date.parse(iso ?? '')
  if (!Number.isFinite(ms)) return ''
  const s = Math.round((ms - nowMs) / 1000)
  const a = Math.abs(s)
  if (a < 45) return rtf.format(0, 'second')
  if (a < 2700) return rtf.format(Math.round(s / 60), 'minute')
  if (a < 64800) return rtf.format(Math.round(s / 3600), 'hour')
  if (a < 86400 * 26) return rtf.format(Math.round(s / 86400), 'day')
  if (a < 86400 * 320) return rtf.format(Math.round(s / (86400 * 30.4)), 'month')
  return rtf.format(Math.round(s / (86400 * 365)), 'year')
}

export function fmtDate(iso) {
  const ms = Date.parse(iso ?? '')
  return Number.isFinite(ms) ? df.format(ms) : ''
}

export function regionLabel(id) { return t(`region.${id}`) }
export function regionArea(id) { return t(`area.${id}`) }
export function kindLabel(kind) { return t(`kind.${kind}`) }

export function tagText(tag) {
  const k = `kind.${tag}`
  return dict[k] !== undefined ? dict[k] : tag
}
