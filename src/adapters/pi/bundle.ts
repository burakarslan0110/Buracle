import { bundleExtension as bundle } from '../shared/bundle'
import { stableJson } from '../omp/render'
import type { PiGenerated } from './runtime/types'

export const BUNDLE_BANNER = '// Buracle Stack extension for Pi. GENERATED by `buracle build` from src/adapters/pi/runtime and canonical/; do not edit.\n'

const GENERATED_MODULE = /[\\/]src[\\/]adapters[\\/]pi[\\/]runtime[\\/]generated-data\.ts$/

/**
 * Pi runs extensions on Node, so the Bun bundle needs what Node names differently: `import.meta.dir` is
 * `import.meta.dirname` (Bun has both), and `import.meta.require` is made with `createRequire`.
 */
export function nodeModuleDirs(text: string): string {
  const out = text.replace(/import\.meta\.dir\b(?!name)/g, 'import.meta.dirname').replace(/import\.meta\.path\b/g, 'import.meta.filename')
  return out.replace('var __require = import.meta.require;', 'import { createRequire as __createRequire } from "node:module";\nvar __require = __createRequire(import.meta.url);')
}

export function generatedModuleSource(data: PiGenerated): string {
  return `// Canonical data baked in by buracle build.\nexport const GENERATED = ${stableJson(data)};\n`
}

export function bundleExtension(repoRoot: string, data: PiGenerated): Promise<string> {
  return bundle({
    repoRoot, entry: 'src/adapters/pi/runtime/extension.ts', dataModule: GENERATED_MODULE, dataSource: generatedModuleSource(data), banner: BUNDLE_BANNER, label: 'pi', transform: nodeModuleDirs,
  })
}
