export interface BuiltFile { path: string; content: string; mode?: number }

export const PORTABLE_PATH_RULES_DIR = '~/.buracle/rules/paths'

const README = `# harness/opencode (generated)

Generated by \`buracle build\` from \`canonical/\` and \`src/adapters/opencode/\`; do not edit by hand.
\`buracle install\` copies or merges these into the OpenCode v2 config dir (\`~/.config/opencode\`):

| File | Installed as |
|---|---|
| \`plugins/buracle/index.js\` | server plugin (auto-discovered package directory): hooks, workflow commands, default effort |
| \`plugins/buracle/tui.js\` | TUI plugin: the status line (\`prompt.footer.status\`), the workflow band above the prompt (\`session.composer.top\`) and the utility commands |
| \`agents/*.md\` | read-only reviewer subagents |
| \`AGENTS.block.md\` | managed block in \`~/.config/opencode/AGENTS.md\` |
| \`config/opencode.fragment.jsonc\` | keys merged into \`opencode.jsonc\` (or \`opencode.json\`) |
| \`config/cli.fragment.jsonc\` | keys merged into \`cli.json\` |

Skills are not here: OpenCode reads the shared render in \`~/.agents/skills\`. The path rules the
AGENTS.md block lists are written to \`~/.buracle/rules/paths/\` by the core install step (shared with Codex).

## Commands

- **Workflows** (\`manifest.json\` \`commands.workflow\`): one \`/<id>\` command per user-invocable skill,
  registered by the server plugin. Each records the workflow start for the band and sends the request
  with the skill attached. Buracle ships no \`commands/<id>.md\` files any more: a file of the same name
  would win over the plugin command, so \`buracle install\` removes the files earlier versions wrote.
- **Utilities** (\`commands.utility\`): \`/remember <text>\` (a memory capture), \`/brain\` (the brain
  web UI), \`/aside <question>\` (a read-only side question, handed to OpenCode's own \`/btw\`),
  \`/buracle-status [status|memory|plan|flow]\` (alias \`/buracle\`) and \`/buracle-ping\` (\`pong\`),
  run by the TUI plugin without a model turn. When another command already uses \`remember\`,
  \`brain\` or \`aside\`, they are \`/buracle-remember\`, \`/buracle-brain\` and \`/buracle-aside\`; when
  one uses \`buracle\`, the alias is left out.

## Install notes

- **One-time restart of the background service.** OpenCode v2 runs plugins in a shared background
  service that does not inherit your terminal's environment, so \`buracle install\` records
  \`BURACLE_HOME\` there with \`opencode service set env BURACLE_HOME <path>\`. OpenCode stops a running
  service when that value changes, and the next OpenCode client starts it again with the new
  environment; restart OpenCode windows that were open during the install. Later installs with the
  same value skip this step, and \`buracle uninstall\` / \`buracle rollback\` undo it with
  \`opencode service unset env BURACLE_HOME\`.
- **Default effort.** \`effort.opencode\` (\`auto\` = xhigh) is applied by the server plugin to every
  available model that has a variant of that level; nothing is written into \`opencode.jsonc\`. Your own
  model settings and a variant picked in the TUI still win.
- The plugin bundles are copies, not links: after \`git pull\`, run \`buracle install\` (it builds, then installs).
- \`BURACLE_NO_CAPTURE=1\` in the service environment turns off memory capture for new sessions.
`

function homes(): string[] {
  const out: string[] = []
  const account = accountHome()
  if (account !== undefined) out.push(account)
  try { out.push(os.userInfo().homedir) } catch {  }
  const h = process.env['HOME']
  if (h !== undefined && h !== '') out.push(h)
  return [...new Set(out.filter(x => x !== '/' && x !== ''))]
}

export function commandNames(c: CanonicalBundle): { workflow: string[], utility: string[] } {
  return { workflow: workflowCommandSkills(catalogSkills(c.skills)).map(s => s.id), utility: [...UTILITY_COMMANDS].sort() }
}

export async function buildFiles(ctx: AdapterContext): Promise<BuiltFile[]> {
  const c = ctx.canonical
  const leakRoots = homes()
  const version = runtimeVersion(ctx.repoRoot)
  const server = await bundleEntry(ctx.repoRoot, 'server', bakedData(c, { withLayout: false, ...(version !== undefined ? { version } : {}) }), { homes: leakRoots })
  const tui = await bundleEntry(ctx.repoRoot, 'tui', bakedData(c, { withLayout: true }), { homes: leakRoots })
  const files: BuiltFile[] = [
    { path: `${PLUGIN_DIR}/index.js`, content: server },
    { path: `${PLUGIN_DIR}/tui.js`, content: tui },
    { path: 'AGENTS.block.md', content: agentsBlock(c, PORTABLE_PATH_RULES_DIR) },
    { path: 'config/opencode.fragment.jsonc', content: configFragmentText(c, PORTABLE_SHIM) },
    { path: 'config/cli.fragment.jsonc', content: cliFragmentText() },
    { path: 'README.md', content: README },
  ]
  for (const a of [...c.agents].sort((x, y) => (x.id < y.id ? -1 : 1))) files.push({ path: `agents/${a.id}.md`, content: renderAgent(a) })
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
  const manifest = {
    harness: 'opencode',
    testedWith: TESTED_WITH,
    minVersion: MIN_VERSION,
    contentHash: contentHash(c),
    commands: commandNames(c),
    files: Object.fromEntries(files.map(f => [f.path, sha256(f.content)])),
  }
  files.push({ path: 'manifest.json', content: JSON.stringify(manifest, null, 2) + '\n' })
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
  return files
}
