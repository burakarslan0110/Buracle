import { join } from 'node:path'
import { repoRelativeModuleComments } from '../shared/bundle'
import type { BakedData } from './runtime/baked'

export type BundleEntry = 'server' | 'tui'

const ENTRY_FILES: Readonly<Record<BundleEntry, string>> = {
  server: 'src/adapters/opencode/runtime/server.ts',
  tui: 'src/adapters/opencode/runtime/tui.tsx',
}

export const TUI_EXTERNALS: readonly string[] = ['solid-js', 'solid-js/*', '@opentui/*', '@opencode/*']

const HEADER: Readonly<Record<BundleEntry, string>> = {
  server: '// Buracle server plugin for OpenCode v2. Generated by `buracle build` from src/adapters/opencode/runtime/server.ts; do not edit.\n',
  tui: '// Buracle TUI status line for OpenCode v2. Generated by `buracle build` from src/adapters/opencode/runtime/tui.tsx; do not edit.\n',
}

export function absolutePathLeaks(text: string, roots: readonly string[]): string[] {
  const found: string[] = []
  for (const r of roots) if (r.length > 1 && text.includes(r)) found.push(r)
  return [...new Set(found)]
}

export async function bundleEntry(repoRoot: string, entry: BundleEntry, baked: BakedData, opts: { homes?: string[] } = {}): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(repoRoot, ENTRY_FILES[entry])],
    root: repoRoot,
    target: 'bun',
    format: 'esm',
    minify: false,
    sourcemap: 'none',
    splitting: false,
    define: { BURACLE_BAKED: JSON.stringify(baked) },
    external: entry === 'tui' ? [...TUI_EXTERNALS] : [],
  })
  if (!result.success) {
    const logs = result.logs.map(l => String(l)).join('\n')
    throw new Error(`opencode: bundling ${ENTRY_FILES[entry]} failed:\n${logs}`)
  }
  const out = result.outputs.find(o => o.kind === 'entry-point') ?? result.outputs[0]
  if (out === undefined) throw new Error(`opencode: bundling ${ENTRY_FILES[entry]} produced no output`)
  const text = HEADER[entry] + repoRelativeModuleComments((await out.text()).replace(/\r\n/g, '\n'), repoRoot)
  const leaks = absolutePathLeaks(text, [repoRoot, ...(opts.homes ?? [])])
  if (leaks.length > 0) throw new Error(`opencode: bundle ${entry} contains absolute paths: ${leaks.join(', ')}`)
  return text
}
