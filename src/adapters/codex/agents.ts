export function tomlMultiline(s: string): string {
  const text = s.replace(/\r\n/g, '\n')
  if (!text.includes("'''") && !/[\u0000-\u0008\u000B-\u001F\u007F]/.test(text)) {
    return `'''\n${text}${text.endsWith('\n') ? '' : '\n'}'''`
  }
  const escaped = text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"').replace(/[\u0000-\u0008\u000B-\u001F\u007F]/g, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)
  return `"""\n${escaped}${escaped.endsWith('\n') ? '' : '\n'}"""`
}

function modelFor(agent: AgentDoc): string | undefined {
  const m = agent.frontmatter['model']
  if (typeof m === 'string') return undefined
  if (m === null || typeof m !== 'object') return undefined
  const v = (m as Record<string, unknown>)['codex']
  return typeof v === 'string' && v.trim() !== '' && v !== 'inherit' ? v : undefined
}

export function codexAgentToml(agent: AgentDoc, opts: { skills?: readonly string[], agents?: readonly string[] } = {}, warnings: string[] = []): string {
  const description = oneLine(typeof agent.frontmatter['description'] === 'string' ? agent.frontmatter['description'] : '')
  if (description === '') warnings.push(`agents/${agent.id}.md: description is empty`)
  const body = renderMarkdown(agent.body, 'codex', { ...opts, file: agent.file }, warnings).trim()
  if (body === '') warnings.push(`agents/${agent.id}.md: body is empty (Codex rejects an agent without developer_instructions)`)
  const lines = [
    `# Generated by Buracle from canonical/${agent.file}; edits here are overwritten by \`buracle install\`.`,
    `name = ${tomlValue(agent.id)}`,
    `description = ${tomlValue(description)}`,
  ]
  if (agent.frontmatter['access'] === 'read-only') lines.push(`sandbox_mode = ${tomlValue('read-only')}`)
  const model = modelFor(agent)
  if (model !== undefined) lines.push(`model = ${tomlValue(model)}`)
  lines.push(`developer_instructions = ${tomlMultiline(body + '\n')}`)
  return lines.join('\n') + '\n'
}

export function reviewAgentIds(agents: readonly AgentDoc[]): string[] {
  return agents.filter(a => a.frontmatter['output'] === 'json').map(a => a.id).sort()
}

function shortGlob(g: string): string {
  return g.replace(/^\*\*\//, '')
}

export interface AgentsBlockInput {
  rules: readonly RuleDoc[]
  pathRulesDir: string
  skills?: readonly string[]
  agents?: readonly string[]
  skillDocs?: readonly SkillDoc[]
  contextMode?: boolean
}

export function codexWorkflowForms(skills: readonly SkillDoc[]): string[] {
  return skills
    .filter(s => s.frontmatter['invocation'] === 'explicit' && s.frontmatter['user-invocable'] !== false)
    .map(s => s.id).sort().map(id => `\`$${id}\``)
}

export function codexCommandsSection(skills: readonly SkillDoc[], opts: { contextMode?: boolean } = {}): string {
  const forms = codexWorkflowForms(skills)
  return [
    '# Buracle commands in Codex',
    '',
    `Codex has no custom slash commands. Where the other harnesses use \`/<id>\`, the user starts a Buracle workflow here with \`$<id>\`${forms.length > 0 ? ` (${forms.join(', ')})` : ''}; any other skill is \`$<id>\` too. Buracle's own commands have these equivalents in Codex; run them for the user when they ask for one:`,
    '- `/remember <text>`: `buracle mem remember -- "<text>"` saves it to memory as a capture; for a typed memory, follow the `$memory` protocol (memory_search, then memory_write).',
    '- `/brain`: `buracle mem ui --open` starts the brain web UI and opens it.',
    '- `/brain review`: `buracle mem ui --open --page review` opens the review page, where the user reads plans, build contracts, PRDs and your changes and pins notes to them; `buracle plan notes --json` reads the open notes.',
    '- `/buracle-status`: `buracle plan status --json`, `buracle flow status` and `buracle mem status` show the plan, the running workflow and the memory.',
    ...(opts.contextMode === true ? [`- What context-mode kept out of the context (the other harnesses show it in the status line): call \`${cmToolName('codex', 'ctx_stats')}\`, or run \`buracle ctx stats --harness codex\` in the project folder.`] : []),
    '- `/aside <question>`: Codex\'s own `/side` asks a side question without changing this conversation.',
  ].join('\n')
}

export function codexAgentsBlock(input: AgentsBlockInput, warnings: string[] = []): string {
  const opts = { skills: input.skills, agents: input.agents }
  const always = input.rules.filter(r => r.scope === 'always').sort((a, b) => (a.id < b.id ? -1 : 1))
  const paths = input.rules.filter(r => r.scope === 'paths').sort((a, b) => (a.id < b.id ? -1 : 1))
  const parts: string[] = [
    '_Managed by Buracle (`buracle install`). The source is `canonical/rules/` in the Buracle repo; edits inside this block stop future updates of it._',
  ]
  for (const r of always) parts.push(renderMarkdown(r.body, 'codex', { ...opts, file: r.file }, warnings).trim())
  parts.push([
    '# Memory',
    '',
    '- Each session starts with a short Buracle memory text: the user\'s profile, the project\'s memories and the person\'s (one CortexDB brain per project under `~/.buracle/brain`), titles and one-line summaries with ids.',
    '- Treat it as a table of contents. Fetch details with the `buracle-memory` MCP tools: `memory_search`, then `memory_get`; `memory_status` shows its health.',
    '- Without the MCP server, use the CLI twins: `buracle mem search "<q>"`, `buracle mem get <id>`, `buracle mem remember -- "<text>"`.',
    '- Codex\'s own memories feature stays off and nothing is written to `~/.codex/memories`; Buracle\'s brain is the single memory.',
  ].join('\n'))
  parts.push(codexCommandsSection(input.skillDocs ?? [], { contextMode: input.contextMode === true }))
  if (paths.length > 0) {
    const rows = paths.map(r => {
      const globs = pathGlobs(r).map(g => `\`${shortGlob(g)}\``).join(', ')
      return `| ${r.id} | ${globs === '' ? '—' : globs} | \`${input.pathRulesDir}/${r.id}.md\` |`
    })
    parts.push([
      '# Path-scoped rules',
      '',
      'Before you edit or create a file that matches a pattern below, read that rule file once per session and follow it.',
      '',
      '| Rule | Files | Read |',
      '|---|---|---|',
      ...rows,
    ].join('\n'))
  }
  return parts.join('\n\n') + '\n'
}
