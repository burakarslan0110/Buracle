import { createHash } from 'node:crypto'

export const HOOK_COMMAND_PREFIX = '"${BURACLE_HOME:-$HOME/.buracle}/bin/buracle" hook codex '

export const LEGACY_HOOK_COMMAND_PREFIX = '"$HOME/.buracle/bin/buracle" hook codex '

export const LEGACY_HOOK_COMMAND_PREFIXES: readonly string[] = [LEGACY_HOOK_COMMAND_PREFIX]

export function hookCommand(event: string, prefix: string = HOOK_COMMAND_PREFIX): string {
  return `${prefix}${event}`
}

export function isBuracleCommand(command: unknown): boolean {
  return typeof command === 'string' && /(?:^|["'\s/])buracle["']?\s+hook\s+codex(?:\s|$)/.test(command.trim())
}

export type CodexHookEvent =
  | 'SessionStart' | 'UserPromptSubmit' | 'PreToolUse' | 'PermissionRequest' | 'PostToolUse' | 'PreCompact'
  | 'PostCompact' | 'Stop' | 'SubagentStart' | 'SubagentStop' | 'SessionEnd'

export const CODEX_HOOK_EVENTS: readonly CodexHookEvent[] = [
  'SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PermissionRequest', 'PostToolUse', 'PreCompact', 'PostCompact', 'Stop', 'SubagentStart', 'SubagentStop', 'SessionEnd',
]

const EVENT_LABEL: Readonly<Record<string, string>> = {
  PreToolUse: 'pre_tool_use', PermissionRequest: 'permission_request', PostToolUse: 'post_tool_use',
  PreCompact: 'pre_compact', PostCompact: 'post_compact', SessionStart: 'session_start', SessionEnd: 'session_end',
  UserPromptSubmit: 'user_prompt_submit', SubagentStart: 'subagent_start', SubagentStop: 'subagent_stop',
  Stop: 'stop', Interrupt: 'interrupt',
}

const EVENTS_WITH_MATCHERS = new Set(['PreToolUse', 'PermissionRequest', 'PostToolUse', 'PreCompact', 'PostCompact', 'SessionStart', 'SessionEnd', 'SubagentStart', 'SubagentStop'])
const EVENTS_WITH_CONTEXT = new Set(['PreToolUse', 'PostToolUse', 'SessionStart', 'UserPromptSubmit', 'SubagentStart'])
const DEFAULT_CONTEXT_LIMIT = 2500
const SESSION_END_MAX_TIMEOUT = 3

export interface CodexCommandHandler {
  type: 'command'
  command: string
  commandWindows?: string
  timeout: number
  async?: boolean
  statusMessage?: string
}
export interface CodexMatcherGroup { matcher?: string, hooks: CodexCommandHandler[] }
export interface CodexHooksFile { description?: string, hooks: Partial<Record<CodexHookEvent, CodexMatcherGroup[]>> }

export const PRE_TOOL_MATCHER = '^(Bash|apply_patch|request_user_input|request_user_input_async|mcp__.+)$'
export const POST_PATCH_MATCHER = 'apply_patch'
export const POST_CAPTURE_MATCHER = '^(Bash|webrun|mcp__.+)$'
export const POST_MASK_MATCHER = '^(Bash|mcp__.+)$'
export const POST_MASK_HANDLER = 'PostToolUseMask'
export const POST_ANSWER_MATCHER = 'request_user_input'
export const PERMISSION_MATCHER = '^(Bash|mcp__.+)$'

function handler(prefix: string, event: string, timeout: number, extra: Partial<CodexCommandHandler> = {}, windowsPrefix?: string): CodexCommandHandler {
  const h: CodexCommandHandler = { type: 'command', command: hookCommand(event, prefix), timeout, ...extra }
  if (windowsPrefix !== undefined) h.commandWindows = hookCommand(event, windowsPrefix)
  return h
}

export function windowsHookPrefix(shim: string): string {
  return `"${shim.replace(/\//g, '\\')}" hook codex `
}

export function buracleHookGroups(prefix: string = HOOK_COMMAND_PREFIX, windowsPrefix?: string): Record<CodexHookEvent, CodexMatcherGroup[]> {
  const h = (event: CodexHookEvent | typeof POST_MASK_HANDLER, timeout: number, extra: Partial<CodexCommandHandler> = {}) => handler(prefix, event, timeout, extra, windowsPrefix)
  return {
    SessionStart: [{ hooks: [h('SessionStart', 15)] }],
    UserPromptSubmit: [{ hooks: [h('UserPromptSubmit', 10)] }],
    PreToolUse: [{ matcher: PRE_TOOL_MATCHER, hooks: [h('PreToolUse', 10)] }],
    PermissionRequest: [{ matcher: PERMISSION_MATCHER, hooks: [h('PermissionRequest', 10)] }],
    PostToolUse: [
      { matcher: POST_PATCH_MATCHER, hooks: [h('PostToolUse', 45, { statusMessage: 'Buracle: checking edited files' })] },
      { matcher: POST_CAPTURE_MATCHER, hooks: [h('PostToolUse', 15, { async: true })] },
      { matcher: POST_MASK_MATCHER, hooks: [h(POST_MASK_HANDLER, 10)] },
      { matcher: POST_ANSWER_MATCHER, hooks: [h('PostToolUse', 10)] },
    ],
    PreCompact: [{ hooks: [h('PreCompact', 20)] }],
    PostCompact: [{ hooks: [h('PostCompact', 10, { async: true })] }],
    Stop: [{ hooks: [h('Stop', 20)] }],
    SubagentStart: [{ hooks: [h('SubagentStart', 10)] }],
    SubagentStop: [{ hooks: [h('SubagentStop', 10)] }],
    SessionEnd: [{ hooks: [h('SessionEnd', SESSION_END_MAX_TIMEOUT)] }],
  }
}

export function buracleHooksFile(prefix: string = HOOK_COMMAND_PREFIX, windowsPrefix?: string): CodexHooksFile {
  const groups = buracleHookGroups(prefix, windowsPrefix)
  const hooks: CodexHooksFile['hooks'] = {}
  for (const e of CODEX_HOOK_EVENTS) hooks[e] = groups[e]
  return {
    description: 'Buracle hooks for Codex CLI (generated by `buracle build`). Each command is a constant `buracle hook codex <Event>` call, so approving them once in /hooks survives Buracle updates.',
    hooks,
  }
}

export function renderHooksJson(file: CodexHooksFile): string {
  return JSON.stringify(file, null, 2) + '\n'
}

export const HOOK_GROUP_IDENTITY: readonly string[] = ['matcher', 'hooks.0.command']

function isRecord(x: unknown): x is Record<string, unknown> {
  return x !== null && typeof x === 'object' && !Array.isArray(x)
}

export function hookEventLabel(event: string): string | undefined {
  return EVENT_LABEL[event]
}

export function hookTrustKey(sourcePath: string, event: string, groupIndex: number, handlerIndex: number): string {
  return `${sourcePath}:${hookEventLabel(event) ?? event}:${groupIndex}:${handlerIndex}`
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys)
  if (isRecord(v)) {
    const o: Record<string, unknown> = {}
    for (const k of Object.keys(v).sort()) if (v[k] !== undefined && v[k] !== null) o[k] = sortKeys(v[k])
    return o
  }
  return v
}

export function hookTrustHash(event: string, group: { matcher?: unknown }, h: Record<string, unknown>, platform: string = process.platform): string | undefined {
  if (h['type'] !== 'command' || typeof h['command'] !== 'string') return undefined
  const command = platform === 'win32' && typeof h['commandWindows'] === 'string' && h['commandWindows'].trim() !== '' ? h['commandWindows'] : h['command']
  const label = hookEventLabel(event)
  if (label === undefined) return undefined
  const raw = typeof h['timeout'] === 'number' && Number.isInteger(h['timeout']) && h['timeout'] >= 0 ? h['timeout'] : undefined
  const timeout = event === 'SessionEnd' || event === 'Interrupt'
    ? Math.min(Math.max(raw ?? 1, 1), SESSION_END_MAX_TIMEOUT)
    : Math.max(raw ?? 600, 1)
  const normalized: Record<string, unknown> = { type: 'command', command, timeout, async: h['async'] === true }
  if (typeof h['statusMessage'] === 'string') normalized['statusMessage'] = h['statusMessage']
  const limit = h['additionalContextLimit']
  if (EVENTS_WITH_CONTEXT.has(event) && typeof limit === 'number' && limit !== DEFAULT_CONTEXT_LIMIT) normalized['additionalContextLimit'] = limit
  const identity: Record<string, unknown> = { event_name: label, hooks: [normalized] }
  if (EVENTS_WITH_MATCHERS.has(event) && typeof group.matcher === 'string') identity['matcher'] = group.matcher
  return `sha256:${createHash('sha256').update(JSON.stringify(sortKeys(identity))).digest('hex')}`
}

export interface FoundHandler { event: string, groupIndex: number, handlerIndex: number, key: string, hash: string | undefined, command: string }

export function findBuracleHandlers(parsed: unknown, sourcePath: string): FoundHandler[] {
  const out: FoundHandler[] = []
  if (!isRecord(parsed) || !isRecord(parsed['hooks'])) return out
  for (const [event, groups] of Object.entries(parsed['hooks'])) {
    if (!Array.isArray(groups)) continue
    groups.forEach((g, gi) => {
      if (!isRecord(g) || !Array.isArray(g['hooks'])) return
      g['hooks'].forEach((h, hi) => {
        if (!isRecord(h) || !isBuracleCommand(h['command'])) return
        const command = process.platform === 'win32' && typeof h['commandWindows'] === 'string' ? h['commandWindows'] : h['command']
        out.push({ event, groupIndex: gi, handlerIndex: hi, key: hookTrustKey(sourcePath, event, gi, hi), hash: hookTrustHash(event, g, h), command: String(command) })
      })
    })
  }
  return out
}

export function duplicateBuracleHandlers(found: readonly FoundHandler[], parsed: unknown): string[] {
  const hooks = isRecord(parsed) && isRecord(parsed['hooks']) ? parsed['hooks'] : {}
  const seen = new Set<string>()
  const dups: string[] = []
  for (const h of found) {
    const groups = hooks[h.event]
    const g = Array.isArray(groups) ? groups[h.groupIndex] : undefined
    const matcher = EVENTS_WITH_MATCHERS.has(h.event) && isRecord(g) && typeof g['matcher'] === 'string' ? g['matcher'] : ''
    const k = `${h.event}\0${matcher}`
    if (seen.has(k)) dups.push(`${h.event}#${h.groupIndex}`)
    else seen.add(k)
  }
  return dups
}

export interface TrustMigration {
  moves: Array<{ from: string, to: string, state: Record<string, unknown> }>
  drops: Array<{ key: string, state: Record<string, unknown> }>
}

export function trustMigration(sourcePath: string, parsedHooks: unknown, removed: ReadonlyArray<{ event: string, groupIndex: number }>, state: Record<string, unknown>): TrustMigration {
  const out: TrustMigration = { moves: [], drops: [] }
  const hooks = isRecord(parsedHooks) && isRecord(parsedHooks['hooks']) ? parsedHooks['hooks'] : {}
  const events = [...new Set(removed.map(r => r.event))].sort()
  for (const event of events) {
    const groups = hooks[event]
    if (!Array.isArray(groups)) continue
    const gone = [...new Set(removed.filter(r => r.event === event).map(r => r.groupIndex))].sort((a, b) => a - b)
    for (const r of gone) {
      const g = groups[r]
      const count = isRecord(g) && Array.isArray(g['hooks']) ? g['hooks'].length : 1
      for (let j = 0; j < count; j++) {
        const key = hookTrustKey(sourcePath, event, r, j)
        const st = state[key]
        if (isRecord(st)) out.drops.push({ key, state: st })
      }
    }
    groups.forEach((g, i) => {
      if (gone.includes(i) || !isRecord(g) || !Array.isArray(g['hooks'])) return
      const shift = gone.filter(r => r < i).length
      if (shift === 0) return
      g['hooks'].forEach((h, j) => {
        if (!isRecord(h)) return
        const from = hookTrustKey(sourcePath, event, i, j)
        const st = state[from]
        if (!isRecord(st)) return
        const approved = typeof st['trusted_hash'] === 'string' && st['trusted_hash'] === hookTrustHash(event, g, h)
        if (approved || st['enabled'] === false) out.moves.push({ from, to: hookTrustKey(sourcePath, event, i - shift, j), state: st })
      })
    })
  }
  return out
}
