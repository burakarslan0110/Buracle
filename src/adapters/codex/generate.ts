import type { CanonicalBundle } from '../../core/catalog'
import type { BuracleConfig } from '../../core/config'
import { codexAgentToml, codexAgentsBlock } from './agents'
import { BYPASS_KEYS, codexMcpTables, codexTui, codexValueProblems, compactKeys, effortKeys, MEMORY_KEYS, renderTomlTables, routingRootKeys, teamsKeys, UPDATE_PLAN_TABLE, updatePlanTable, type CodexTui, type McpTable } from './config'
import { renderRulesFile } from './execpolicy'
import { buracleHooksFile, renderHooksJson, type CodexHooksFile } from './hooks-config'
import { mdBlockMarkers, tomlKey, tomlValue } from '../../engine/merge'
import { pathRuleFiles } from '../shared/rules'

export const OWNER = 'codex'
export const AGENTS_BLOCK_ID = 'buracle'
export const RULES_FILE = 'buracle.rules'

export interface CodexArtifacts {
  hooksFile: CodexHooksFile
  mcpTables: Record<string, McpTable>
  tui: CodexTui
  rootKeys: Record<string, unknown>
  effortKeys?: Record<string, string>
  bypassKeys?: Record<string, unknown>
  teamsKeys?: Record<string, boolean>
  memoryKeys?: Record<string, boolean>
  compactKeys?: Record<string, string>
  agentsBlock: string
  agentFiles: Array<{ id: string, content: string }>
  rulesFile: string
  pathRules: Array<{ id: string, content: string }>
  warnings: string[]
}

export type ArtifactConfig = Pick<BuracleConfig, 'routing' | 'effort' | 'permissions' | 'agents'>

export interface ArtifactInput {
  canonical: Pick<CanonicalBundle, 'mcp' | 'rules' | 'skills' | 'agents' | 'statusline'>
  buracle: string
  pathRulesDir: string
  config?: ArtifactConfig
  home?: string
  hookCommandPrefix?: string
  hookCommandPrefixWindows?: string
}

export class CodexValueError extends Error {
  constructor(readonly problems: readonly string[]) {
    super(`refusing to write values Codex 0.161 does not accept (it would not start): ${problems.join('; ')}`)
    this.name = 'CodexValueError'
  }
}

export function codexArtifacts(input: ArtifactInput): CodexArtifacts {
  const warnings: string[] = []
  const c = input.canonical
  const cfg = input.config
  const refs = { skills: c.skills.map(s => s.id), agents: c.agents.map(a => a.id) }
  const bypass = cfg?.permissions.bypass === true
  const mcpTables = codexMcpTables(c.mcp, input.buracle, warnings, { approve: bypass })
  const rootKeys = cfg !== undefined ? routingRootKeys(cfg) : {}
  const effort = cfg !== undefined ? effortKeys(cfg) : undefined
  const bypassKeys = bypass ? { ...BYPASS_KEYS } : undefined
  const problems = codexValueProblems({ mcpTables, rootKeys, ...(effort !== undefined ? { effort } : {}), ...(bypassKeys !== undefined ? { bypass: bypassKeys } : {}) })
  if (problems.length > 0) throw new CodexValueError(problems)
  const out: CodexArtifacts = {
    hooksFile: buracleHooksFile(input.hookCommandPrefix, input.hookCommandPrefixWindows),
    mcpTables,
    tui: codexTui(c.statusline, warnings),
    rootKeys,
    agentsBlock: codexAgentsBlock({ rules: c.rules, pathRulesDir: input.pathRulesDir, skillDocs: c.skills, ...refs }, warnings),
    agentFiles: [...c.agents].sort((a, b) => (a.id < b.id ? -1 : 1)).map(a => ({ id: a.id, content: codexAgentToml(a, refs, warnings) })),
    rulesFile: renderRulesFile({ ...(input.home !== undefined ? { home: input.home } : {}), shim: input.buracle }),
    pathRules: pathRuleFiles(c, warnings).map(r => ({ id: r.id, content: r.content })),
    warnings,
  }
  if (effort !== undefined) out.effortKeys = effort
  if (bypassKeys !== undefined) out.bypassKeys = bypassKeys
  const teams = cfg !== undefined ? teamsKeys(cfg) : undefined
  if (teams !== undefined) out.teamsKeys = teams
  out.memoryKeys = { ...MEMORY_KEYS }
  out.compactKeys = compactKeys()
  return out
}

export function agentsBlockWithMarkers(content: string): string {
  const m = mdBlockMarkers(AGENTS_BLOCK_ID)
  return `${m.start}\n${content.replace(/\n+$/, '')}\n${m.end}\n`
}

function rootLines(keys: Record<string, unknown>): string[] {
  return Object.entries(keys).map(([k, v]) => `${k.split('.').map(tomlKey).join('.')} = ${tomlValue(v)}`)
}

export function configFragment(a: CodexArtifacts): string {
  const header = [
    '# Buracle-managed parts of ~/.codex/config.toml (generated by `buracle build` from the default',
    '# config). `buracle install` merges them into the live config: each [mcp_servers.<id>] and',
    '# [tools.update_plan] as a table, the [tui] keys and the root keys below one by one. Every other',
    '# key, table and comment stays. A value you changed is kept, except the no-approval keys while',
    '# permissions.enforce is on; the reasoning-effort keys follow config effort.codex and keep a level',
    '# you (or a Codex model migration) set. {buracle} is replaced with the absolute path of the',
    '# Buracle shim. Secrets are forwarded with env_vars, never written.',
  ]
  const roots: string[] = []
  if (Object.keys(a.rootKeys).length > 0) roots.push('# Routing: MCP tools on the first turn; the built-in web search is off while routing is enforced.', ...rootLines(a.rootKeys))
  if (a.effortKeys !== undefined) roots.push('# Default reasoning effort (config effort.codex).', ...rootLines(a.effortKeys))
  if (a.teamsKeys !== undefined) roots.push('# agents.teams: Codex agent threads (spawn_agent, wait_agent) stay on; a value you set is kept.', ...rootLines(a.teamsKeys))
  if (a.memoryKeys !== undefined) roots.push('# Codex native memories stay off: the Buracle brain is the one memory; a value you set is kept.', ...rootLines(a.memoryKeys))
  if (a.compactKeys !== undefined) roots.push('# The summary prompt of local compaction (providers Codex does not compact remotely); a value you set is kept.', ...rootLines(a.compactKeys))
  if (a.bypassKeys !== undefined) roots.push('# permissions.bypass: Codex asks nothing except the H20 consent prompts of Buracle\'s execpolicy rule; every other approval is rejected or answered by Buracle\'s hooks (both keys or neither).', ...rootLines(a.bypassKeys))
  const tables: Array<readonly [string, Record<string, unknown>]> = [
    ...Object.entries(a.mcpTables),
    ['tui', { status_line: a.tui.status_line, terminal_title: a.tui.terminal_title }],
    [UPDATE_PLAN_TABLE, updatePlanTable()],
  ]
  const head = [header.join('\n'), ...(roots.length > 0 ? [roots.join('\n')] : [])]
  return `${head.join('\n\n')}\n\n${renderTomlTables(tables)}`
}

export function codexBuildFiles(canonical: ArtifactInput['canonical'] & Pick<CanonicalBundle, 'config'>): { files: Array<{ path: string, content: string }>, warnings: string[] } {
  const a = codexArtifacts({ canonical, buracle: '{buracle}', pathRulesDir: '~/.buracle/rules/paths', config: canonical.config })
  const files = [
    { path: 'hooks.json', content: renderHooksJson(a.hooksFile) },
    { path: 'config.fragment.toml', content: configFragment(a) },
    { path: 'AGENTS.md', content: agentsBlockWithMarkers(a.agentsBlock) },
    { path: `rules/${RULES_FILE}`, content: a.rulesFile },
    ...a.agentFiles.map(f => ({ path: `agents/${f.id}.toml`, content: f.content })),
    ...a.pathRules.map(f => ({ path: `rules/paths/${f.id}.md`, content: f.content })),
  ]
  return { files: files.sort((x, y) => (x.path < y.path ? -1 : x.path > y.path ? 1 : 0)), warnings: a.warnings }
}
