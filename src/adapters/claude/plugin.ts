function str(x: unknown): string | undefined {
  return typeof x === 'string' && x.trim() !== '' ? x.trim() : undefined
}

function fmText(x: unknown, protocols: readonly string[]): string | undefined {
  const s = str(x)
  return s === undefined ? undefined : expandPlaceholders(s, claudePlaceholderFor(protocols))
}

export function protocolIds(skills: readonly SkillDoc[]): string[] {
  return skills.filter(s => s.frontmatter['user-invocable'] === false).map(s => s.id)
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2) + '\n'
}

function sortedJson(value: unknown): string {
  return JSON.stringify(JSON.parse(stableStringify(value)) as unknown, null, 2)
}

function compareStr(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

export function renderSkill(skill: SkillDoc, protocols: readonly string[] = []): GenFile[] {
  const fm = skill.frontmatter
  const description = fmText(fm['description'], protocols)
  if (description === undefined) throw new RenderError(`${skill.dir}/SKILL.md: description is required`)
  const explicit = fm['invocation'] === 'explicit'
  const entries: Array<readonly [string, FrontmatterValue | undefined]> = [
    ['name', skill.id],
    ['description', description],
    ['when_to_use', fmText(fm['when_to_use'], protocols)],
    ['argument-hint', str(fm['argument-hint'])],
    ['disable-model-invocation', explicit ? true : undefined],
    ['user-invocable', fm['user-invocable'] === false ? false : undefined],
  ]
  const out: GenFile[] = [{
    path: `skills/${skill.id}/SKILL.md`,
    content: withFrontmatter(entries, renderClaudeMarkdown(skill.body, `${skill.dir}/SKILL.md`, protocols)),
  }]
  for (const f of skill.files) {
    if (f.path === 'SKILL.md') continue
    const path = `skills/${skill.id}/${f.path}`
    if (f.path.endsWith('.md')) out.push({ path, content: renderClaudeMarkdown(f.content, `${skill.dir}/${f.path}`, protocols) })
    else if (f.path.startsWith('scripts/')) out.push({ path, content: f.content, mode: (f.mode & 0o111) !== 0 ? EXEC : 0o644 })
    else out.push({ path, content: f.content })
  }
  return out
}

export function pluginMcpPattern(server: string): string {
  return `mcp__plugin_${PLUGIN_NAME}_${mcpServerToken('claude', server)}__*`
}

export function pluginMcpRegex(server: string): string {
  const prefix = `mcp__plugin_${PLUGIN_NAME}_${mcpServerToken('claude', server)}__`
  return '^' + prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

export function claudeAgentTools(agent: AgentDoc, mcp: CanonicalBundle['mcp']): string[] {
  const raw = agent.frontmatter['tools']
  const list = Array.isArray(raw) ? raw : typeof raw === 'string' ? raw.split(',') : []
  const out: string[] = []
  const add = (...names: string[]) => { for (const n of names) if (!out.includes(n)) out.push(n) }
  for (const item of list) {
    const t = String(item).trim()
    if (t === '') continue
    if (t.startsWith('mcp:')) {
      const server = t.slice(4)
      const spec = mcp.servers[server]
      if (spec === undefined) throw new RenderError(`${agent.file}: tools lists unknown MCP server ${JSON.stringify(server)}`)
      if (spec.harnesses.includes('claude')) add(pluginMcpPattern(server))
      continue
    }
    switch (t) {
      case 'read': add('Read'); break
      case 'search':
      case 'bash':
      case 'bash-readonly': add('Bash'); break
      case 'edit': add('Edit'); break
      case 'write': add('Write', 'Edit', 'NotebookEdit'); break
      case 'web': add('WebFetch', 'WebSearch'); break
      case 'web_fetch': add('WebFetch'); break
      case 'web_search': add('WebSearch'); break
      default: throw new RenderError(`${agent.file}: unknown abstract tool ${JSON.stringify(t)}`)
    }
  }
  return out
}

function claudeAgentModel(agent: AgentDoc): string | undefined {
  const m = agent.frontmatter['model']
  if (typeof m === 'string') return str(m)
  if (m !== null && typeof m === 'object' && !Array.isArray(m)) return str((m as Record<string, unknown>)['claude'])
  return undefined
}

export function renderAgent(agent: AgentDoc, mcp: CanonicalBundle['mcp'], protocols: readonly string[] = []): GenFile {
  const description = fmText(agent.frontmatter['description'], protocols)
  if (description === undefined) throw new RenderError(`${agent.file}: description is required`)
  const tools = claudeAgentTools(agent, mcp)
  const readOnly = agent.frontmatter['access'] !== 'read-write'
  const entries: Array<readonly [string, FrontmatterValue | undefined]> = [
    ['name', agent.id],
    ['description', description],
    ['tools', tools.length > 0 ? tools.join(', ') : undefined],
    ['disallowedTools', readOnly ? READ_ONLY_DISALLOWED.join(', ') : undefined],
    ['model', claudeAgentModel(agent)],
  ]
  return { path: `agents/${agent.id}.md`, content: withFrontmatter(entries, renderClaudeMarkdown(agent.body, agent.file, protocols)) }
}

export const CLAUDE_MCP_TOOL_TIMEOUT_MS = 100_000_000

function mcpEnv(spec: McpServerSpec): Record<string, string> | undefined {
  const env = mcpEnvFor(spec, 'claude')
  const out: Record<string, string> = {}
  for (const key of Object.keys(env).sort(compareStr)) {
    const v = env[key] as string
    const fwd = envRef(v)
    out[key] = fwd !== undefined ? `\${${fwd}}` : v
  }
  return Object.keys(out).length > 0 ? out : undefined
}

export function mcpJson(mcp: CanonicalBundle['mcp']): Record<string, unknown> {
  const servers: Record<string, unknown> = {}
  for (const id of Object.keys(mcp.servers).sort(compareStr)) {
    const spec = mcp.servers[id] as McpServerSpec
    if (!spec.harnesses.includes('claude')) continue
    let entry: Record<string, unknown>
    if (spec.transport === 'http') {
      entry = { type: 'http', url: spec.url }
    } else {
      const expanded = expandMcpCommand(spec, { buracle: SHIM_MCP, id })
      const viaLauncher = expanded.command === SHIM_MCP
      const command = viaLauncher ? HOOK_COMMAND : expanded.command
      const args = viaLauncher ? [LAUNCHER_ARG, ...expanded.args] : expanded.args
      entry = { command }
      if (args.length > 0) entry['args'] = args
      const env = mcpEnv(spec)
      if (env !== undefined) entry['env'] = env
    }
    if (spec.tool_timeout_sec !== undefined && (spec.tool_timeout_hard === true || spec.tool_timeout_sec * 1000 > CLAUDE_MCP_TOOL_TIMEOUT_MS)) entry['timeout'] = spec.tool_timeout_sec * 1000
    if (spec.critical === true) entry['alwaysLoad'] = true
    servers[id] = entry
  }
  return { mcpServers: servers }
}

export function lspJson(c: CanonicalBundle): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  const servers = c.tools.tools.flatMap(t => (t.lsp !== undefined ? [t.lsp] : [])).sort((a, b) => compareStr(a.id, b.id))
  for (const s of servers) {
    out[s.id] = {
      command: HOOK_COMMAND,
      args: [LAUNCHER_ARG, 'lsp', 'run', s.id],
      extensionToLanguage: Object.fromEntries(Object.keys(s.extensions).sort(compareStr).map(k => [k, s.extensions[k]])),
      restartOnCrash: true,
      maxRestarts: 3,
      ...(s.startup_timeout_ms !== undefined ? { startupTimeout: s.startup_timeout_ms } : {}),
    }
  }
  return out
}

export interface ClassicHook { event: string; matcher?: string; timeout: number; async?: boolean }

const LIFECYCLE = [
  'SessionStart', 'UserPromptExpansion', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'PreCompact', 'PostCompact', 'Stop',
  'SubagentStart', 'SubagentStop', 'SessionEnd',
]

const EXACT_NAME = /^[A-Za-z0-9_ ,-]+$/

export function matcherOf(alternatives: readonly string[]): string {
  const names = alternatives.filter(a => EXACT_NAME.test(a))
  const patterns = alternatives.filter(a => !EXACT_NAME.test(a))
  if (patterns.length === 0) return names.join('|')
  return [...(names.length > 0 ? [`^(?:${names.join('|')})$`] : []), ...patterns].join('|')
}

interface RawHook { event: string; matcher?: string; timeoutMs?: number; async?: boolean; id: string }

function commandBindings(id: string, binding: unknown): RawHook[] {
  if (binding === null || typeof binding !== 'object') return []
  const b = binding as Record<string, unknown>
  const out: RawHook[] = []
  const take = (x: unknown, legacy: boolean) => {
    if (x === null || typeof x !== 'object') return
    const f = x as Record<string, unknown>
    const ev = str(f['event'])
    if (ev === undefined) return
    const event = legacy ? ev : ev.startsWith('classic.') ? ev.slice('classic.'.length) : undefined
    if (event === undefined) return
    if (!/^[A-Z][A-Za-z]+$/.test(event)) throw new RenderError(`hooks.yaml ${id}: invalid claude command hook event ${JSON.stringify(ev)}`)
    if (f['matcher'] !== undefined && typeof f['matcher'] !== 'string') throw new RenderError(`hooks.yaml ${id}: a claude command hook matcher must be a string`)
    const r: RawHook = { event, id }
    const m = str(f['matcher'])
    if (m !== undefined) r.matcher = m
    if (typeof f['timeoutMs'] === 'number' && f['timeoutMs'] > 0) r.timeoutMs = f['timeoutMs']
    if (f['async'] === true) r.async = true
    out.push(r)
  }
  take(b, false)
  for (const a of Array.isArray(b['also']) ? b['also'] : []) take(a, false)
  const fb = b['fallback']
  for (const f of Array.isArray(fb) ? fb : fb === undefined ? [] : [fb]) take(f, true)
  return out
}

export function splitAlternatives(matcher: string): string[] {
  const out: string[] = []
  let depth = 0
  let inClass = false
  let cur = ''
  for (let i = 0; i < matcher.length; i++) {
    const ch = matcher[i] as string
    if (ch === '\\' && i + 1 < matcher.length) { cur += ch + (matcher[i + 1] as string); i++; continue }
    if (inClass) { if (ch === ']') inClass = false }
    else if (ch === '[') inClass = true
    else if (ch === '(') depth++
    else if (ch === ')') depth = Math.max(0, depth - 1)
    else if (ch === '|' && depth === 0) { out.push(cur); cur = ''; continue }
    cur += ch
  }
  out.push(cur)
  return out.map(x => x.trim()).filter(x => x !== '')
}

export function classicHooks(c: CanonicalBundle): ClassicHook[] {
  const fromMatrix = c.hooks.hooks.flatMap(h => commandBindings(h.id, (h.bindings as Record<string, unknown> | undefined)?.['claude']))
  const raw: RawHook[] = fromMatrix.length > 0 ? fromMatrix : CLASSIC_HOOKS.map(h => {
    const r: RawHook = { event: h.event, timeoutMs: h.timeout * 1000, id: 'built-in' }
    if (h.matcher !== undefined) r.matcher = h.matcher
    if (h.async === true) r.async = true
    return r
  })
  const groups = new Map<string, { event: string; async: boolean; matchers: string[] | null; timeoutMs: number }>()
  for (const r of raw) {
    const key = `${r.event}\0${r.async === true ? 'async' : 'sync'}`
    let g = groups.get(key)
    if (g === undefined) { g = { event: r.event, async: r.async === true, matchers: [], timeoutMs: 0 }; groups.set(key, g) }
    if (r.matcher === undefined) g.matchers = null
    else if (g.matchers !== null) for (const part of splitAlternatives(r.matcher)) if (!g.matchers.includes(part)) g.matchers.push(part)
    g.timeoutMs = Math.max(g.timeoutMs, r.timeoutMs ?? 10_000)
  }
  const rank = (e: string) => { const i = LIFECYCLE.indexOf(e); return i < 0 ? LIFECYCLE.length : i }
  const out = [...groups.values()].map((g): ClassicHook => {
    const h: ClassicHook = { event: g.event, timeout: Math.ceil(g.timeoutMs / 1000) }
    if (g.matchers !== null && g.matchers.length > 0 && g.event !== 'SessionStart') h.matcher = matcherOf(withShellToolNames(g.matchers))
    if (g.async) h.async = true
    return h
  })
  return out.sort((a, b) => rank(a.event) - rank(b.event) || compareStr(a.event, b.event) || Number(a.async === true) - Number(b.async === true))
}

function withShellToolNames(names: string[]): string[] {
  const out = [...new Set(names)]
  if (out.includes('Bash')) for (const t of SHELL_TOOLS) if (!out.includes(t)) out.push(t)
  return out
}

export const HOOK_COMMAND = 'bun'
export const LAUNCHER_ARG = '${CLAUDE_PLUGIN_ROOT}/bin/buracle.ts'

/** Exec form (`command` plus `args`): Claude Code spawns bun with no shell, so the same entry runs under sh, Git Bash and PowerShell. */
export function hookArgs(event: string): string[] {
  return [LAUNCHER_ARG, 'hook', 'claude', event]
}

export function hooksJson(classic: readonly ClassicHook[], withModule: boolean): Record<string, unknown> {
  const hooks: Record<string, Array<Record<string, unknown>>> = {}
  for (const h of classic) {
    const handler: Record<string, unknown> = { type: 'command', command: HOOK_COMMAND, args: hookArgs(h.event), timeout: h.timeout }
    // The guards fail closed also when bun cannot start or the hook times out (Claude Code ≥ 2.1.295; older versions ignore the key).
    if (h.event === 'PreToolUse') handler['onFailure'] = 'block'
    if (h.async === true) handler['async'] = true
    const group = h.matcher !== undefined ? { matcher: h.matcher, hooks: [handler] } : { hooks: [handler] }
    ;(hooks[h.event] ??= []).push(group)
  }
  const out: Record<string, unknown> = {
    description: 'Buracle: command hooks are the backbone (guards, consent, stop guard, prompt routing, usage ledger, workflow tracking, memory, compaction, file checks, code indexes); the mod adds the workflow band above the prompt, the consent dialog, turn receipts, panes and commands',
  }
  if (withModule) out['modules'] = ['./register.tsx']
  out['hooks'] = hooks
  return out
}

function claudePlugins(c: CanonicalBundle): string[] {
  return c.plugins.claude.plugins.filter(p => p.enabled).map(p => p.id)
}

export function canonicalContentHash(c: CanonicalBundle): string {
  return valueHash({
    config: c.config, mcp: c.mcp, plugins: c.plugins, tools: c.tools, hooks: c.hooks, routing: c.routing,
    statusline: c.statusline, pricing: c.pricing,
    rules: c.rules.map(r => ({ id: r.id, scope: r.scope, frontmatter: r.frontmatter, body: r.body })),
    skills: c.skills.map(s => ({ id: s.id, files: s.files.map(f => ({ path: f.path, content: f.content, mode: f.mode & 0o111 ? 1 : 0 })) })),
    agents: c.agents.map(a => ({ id: a.id, frontmatter: a.frontmatter, body: a.body })),
  })
}

function tsModule(spec: { name: string, type: string, imports?: string, value: unknown, note: string, assert?: boolean }): string {
  const lines = [GENERATED_HEADER, `// ${spec.note}`]
  if (spec.imports !== undefined) lines.push(`import type { ${spec.imports} } from '../core/index'`)
  const literal = sortedJson(spec.value)
  lines.push('', spec.assert === true
    ? `export const ${spec.name}: ${spec.type} = ${literal} as ${spec.type}`
    : `export const ${spec.name}: ${spec.type} = ${literal}`, '')
  return lines.join('\n')
}

export function generatedModules(c: CanonicalBundle, buracleVersion: string): GenFile[] {
  const mcp: CatalogMcp[] = catalogMcp(c.mcp, 'claude')
  const expand = claudePlaceholderFor(protocolIds(c.skills))
  const skills: CatalogSkill[] = catalogSkills(c.skills).map(s => ({ ...s, description: expandPlaceholders(s.description.trim(), expand) }))
  const catalog = {
    harness: 'claude' as const,
    mcp,
    skills,
    plugins: claudePlugins(c),
    criticalToolPatterns: mcp.filter(s => s.critical).map(s => pluginMcpRegex(s.id)),
  }
  const meta = { buracleVersion, testedWith: TESTED_WITH, minClaude: MIN_CLAUDE, contentHash: canonicalContentHash(c) }
  return [
    {
      path: 'hooks/generated/meta.ts',
      content: tsModule({
        name: 'META', type: '{ buracleVersion: string, testedWith: string, minClaude: string, contentHash: string }', value: meta,
        note: 'Versions; contentHash is the sha256 of the parsed canonical/ tree.',
      }),
    },
    {
      path: 'hooks/generated/catalog.ts',
      content: tsModule({
        name: 'CATALOG', type: "{ mcp: CatalogMcp[], skills: CatalogSkill[], plugins: string[], criticalToolPatterns: string[], harness: 'claude' }",
        imports: 'CatalogMcp, CatalogSkill', value: catalog,
        note: 'Capability catalog. criticalToolPatterns are RegExp sources over full Claude tool names (critical servers: never deferred).',
      }),
    },
  ]
}

