const [REASON_PRE, REASON_POST] = failClosedReason('\u0000').split('\u0000') as [string, string]

export const BIN_BURACLE_TS = `#!/usr/bin/env bun
// GENERATED by \`buracle build\` (src/adapters/claude/plugin.ts). Do not edit.
// Buracle's launcher inside the Claude Code plugin: \`bun <plugin>/bin/buracle.ts <args>\` runs the
// Buracle CLI in this process: the frozen runtime the shim runs, else the checkout. The command hooks,
// MCP servers and language servers use it, and bin/buracle when there is no shim.
import { existsSync, readFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, resolve } from 'node:path'

const HOME = (process.env['HOME'] ?? '').trim() || homedir()
const BURACLE_HOME = (process.env['BURACLE_HOME'] ?? '').trim() || join(HOME, '.buracle')
const REASON_PRE = ${JSON.stringify(REASON_PRE)}
const REASON_POST = ${JSON.stringify(REASON_POST)}

function isCheckout(dir: string): boolean {
  return existsSync(join(dir, 'canonical', 'buracle.yaml')) && existsSync(join(dir, 'src', 'cli', 'router.ts'))
}

/** The tree the shim runs (its frozen runtime, or the checkout), read from the POSIX shim. */
function shimTree(): string | undefined {
  try {
    const text = readFileSync(join(BURACLE_HOME, 'bin', 'buracle'), 'utf8')
    const main = /^m='((?:[^']|'\\\\'')*)'$/m.exec(text)?.[1] ?? /^exec '(?:[^']|'\\\\'')*' '((?:[^']|'\\\\'')*)' "\\$@"$/m.exec(text)?.[1]
    if (main === undefined) return undefined
    const dir = resolve(main.replace(/'\\\\''/g, "'"), '..', '..', '..')
    return isCheckout(dir) ? dir : undefined
  } catch { return undefined }
}

function checkout(): string | undefined {
  const here = resolve(import.meta.dir, '..', '..', '..')
  if (isCheckout(here)) return here
  try {
    const snap = JSON.parse(readFileSync(join(BURACLE_HOME, 'state', 'runtime-config.json'), 'utf8')) as { resolved?: { repoRoot?: unknown } }
    const r = snap.resolved?.repoRoot
    if (typeof r === 'string' && isCheckout(r)) return r
  } catch { /* no snapshot yet */ }
  try {
    const m = /^repo:\\s*['"]?([^'"\\n]+?)['"]?\\s*$/m.exec(readFileSync(join(BURACLE_HOME, 'config.yaml'), 'utf8'))
    const r = m?.[1]?.replace(/^~(?=$|[\\\\/])/, HOME)
    if (r !== undefined && isCheckout(r)) return r
  } catch { /* no config yet */ }
  return undefined
}

const argv = process.argv.slice(2)

/** A hook that cannot run: a guard hook (PreToolUse) denies the call, any other does nothing. */
function failHook(detail: string): never {
  if (argv[2] === 'PreToolUse' && (argv[1] === 'claude' || argv[1] === 'codex')) {
    process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: REASON_PRE + detail + REASON_POST } }) + '\\n')
  }
  process.exit(0)
}

const root = shimTree() ?? checkout()
if (root === undefined) {
  if (argv[0] === 'hook') failHook('no Buracle runtime or checkout was found')
  process.stderr.write("buracle: the Buracle checkout was not found; run 'bun src/cli/main.ts install' in it\\n")
  process.exit(127)
}
let runProcess: (argv: readonly string[]) => Promise<number>
try {
  ({ runProcess } = (await import(join(root, 'src', 'cli', 'router.ts'))) as { runProcess(argv: readonly string[]): Promise<number> })
} catch (e) {
  const why = String(e instanceof Error ? e.message : e).split('\\n')[0] ?? ''
  if (argv[0] === 'hook') failHook(\`Buracle's CLI in \${root} cannot load: \${why}\`)
  process.stderr.write(\`buracle: the CLI in \${root} cannot load: \${why}\\n\`)
  process.exit(1)
}
process.exit(await runProcess(argv))
`

export const BIN_BURACLE_CMD = '@echo off\r\nrem GENERATED by \`buracle build\`. Do not edit.\r\nbun "%~dp0buracle.ts" %*\r\n'

function readme(c: CanonicalBundle, hasTemplate: boolean): string {
  const fallbacks = classicHooks(c).map(h => (h.matcher !== undefined ? `${h.event} ${h.matcher}` : h.event)).join(', ')
  const skills = [...c.skills].map(s => s.id).sort(compareStr)
  const agents = [...c.agents].map(a => a.id).sort(compareStr)
  const servers = catalogMcp(c.mcp, 'claude').map(s => (s.critical ? `${s.id} (always loaded)` : s.id))
  return `# buracle (Claude Code plugin)

This folder is **generated** by \`buracle build\` from \`canonical/\` and \`src/\`; do not edit it by hand.
The repository's \`.claude-plugin/marketplace.json\` declares a local marketplace, and Claude Code reads the
plugin in place from this folder (\`claude plugin marketplace add <repo>\` and
\`claude plugin install buracle@buracle --scope user\`; \`buracle install claude\` runs both).

- Tested with Claude Code ${TESTED_WITH} (oldest supported: ${MIN_CLAUDE}).
- \`hooks/hooks.json\`: the command hooks, Buracle's backbone (${fallbacks}); each runs
  \`bun \${CLAUDE_PLUGIN_ROOT}/bin/buracle.ts hook claude <Event>\` in exec form (no shell, so Git Bash and PowerShell
  start it alike) and always runs; PreToolUse blocks the tool call when the hook cannot start or times out.
- \`hooks/register.tsx\`: the mod, the experience layer (the workflow band above the prompt, the consent dialog, turn receipts, output masking, commands, panes)${hasTemplate ? '' : '; there is no template yet, so this build loads no mod'}.
- \`hooks/core/\`: a copy of \`src/core\`; \`hooks/generated/\`: the capability catalog and the versions the mod reads.
- Skills (\`/<id>\`, the bare alias Buracle's texts use; \`/buracle:<id>\` always works, also when another command took the bare name): ${skills.join(', ')}.
- Agents (\`buracle:<id>\`, read-only): ${agents.join(', ')}.
- MCP servers (\`mcp__plugin_buracle_<server>__*\`): ${servers.join(', ')}; \`.lsp.json\`: language servers (from Buracle's toolchain).
- \`bin/\`: \`buracle\` (on the Bash tool's PATH), \`buracle.ts\` (the launcher of the hooks, the MCP and the language servers), \`buracle.cmd\` (Windows, on the PowerShell tool's PATH).
- \`settings.json\`: \`subagentStatusLine\` (plugin settings accept only \`agent\` and \`subagentStatusLine\`).

Checks: \`claude plugin validate --strict --json harness/claude\` (must pass with no error and no warning) and
\`claude plugin test harness/claude\`.
`
}

export function templateTarget(rel: string): string | undefined {
  if (rel === 'register.tsx') return 'hooks/register.tsx'
  if (rel === 'types/index.d.ts' || rel === 'README.md') return rel
  if (rel.startsWith('tests/')) return rel
  return undefined
}

export function generatePlugin(input: PluginInput): GenFile[] {
  const c = input.canonical
  const template = new Map(input.templateFiles.map(f => [f.path, f]))
  const hasModule = template.has('register.tsx')
  const hasTypes = template.has('types/index.d.ts')

  const files: GenFile[] = []
  files.push({ path: '.claude-plugin/plugin.json', content: json(pluginJson(hasTypes, input.buracleVersion)) })
  files.push({ path: 'hooks/hooks.json', content: json(hooksJson(classicHooks(c), hasModule)) })
  files.push(...generatedModules(c, input.buracleVersion))
  for (const f of [...input.coreFiles].sort((a, b) => compareStr(a.path, b.path))) {
    if (f.path.endsWith('.ts')) files.push({ path: `hooks/core/${f.path}`, content: f.content })
  }
  const protocols = protocolIds(c.skills)
  for (const s of [...c.skills].sort((a, b) => compareStr(a.id, b.id))) files.push(...renderSkill(s, protocols))
  for (const a of [...c.agents].sort((x, y) => compareStr(x.id, y.id))) files.push(renderAgent(a, c.mcp, protocols))
  files.push({ path: '.mcp.json', content: json(mcpJson(c.mcp)) })
  const lsp = lspJson(c)
  if (Object.keys(lsp).length > 0) files.push({ path: '.lsp.json', content: json(lsp) })
  files.push({ path: 'bin/buracle', content: BIN_BURACLE, mode: EXEC })
  files.push({ path: 'bin/buracle.ts', content: BIN_BURACLE_TS, mode: EXEC })
  files.push({ path: 'bin/buracle.cmd', content: BIN_BURACLE_CMD })
  files.push({ path: 'settings.json', content: json(SETTINGS_JSON) })
  if (!template.has('README.md')) files.push({ path: 'README.md', content: readme(c, hasModule) })

  const taken = new Map(files.map(f => [f.path, 'generated']))
  for (const f of [...input.templateFiles].sort((a, b) => compareStr(a.path, b.path))) {
    const target = templateTarget(f.path)
    if (target === undefined) continue
    if (taken.has(target)) throw new RenderError(`template file ${f.path} would overwrite the generated ${target}`)
    taken.set(target, 'template')
    const out: GenFile = { path: target, content: f.content }
    if (((f.mode ?? 0) & 0o111) !== 0) out.mode = EXEC
    files.push(out)
  }
  return files.sort((a, b) => compareStr(a.path, b.path))
}
