function banner(source: string): string {
  return `<!-- Generated by \`buracle build\` from ${source}. Do not edit by hand: change the source and run \`buracle build\`; \`buracle build --check\` reports any drift. -->\n\n`
}

function cell(s: string): string {
  return s.replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim()
}

function prose(s: string): string {
  return cell(s).replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

function code(s: string): string {
  const t = s.includes('`') ? `\`\` ${s} \`\`` : `\`${s}\``
  return cell(t)
}

function mdTable(head: readonly string[], rows: readonly (readonly string[])[]): string {
  const lines = [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`]
  for (const r of rows) lines.push(`| ${r.join(' | ')} |`)
  return lines.join('\n') + '\n'
}

function finish(text: string): string {
  return text.replace(/\n{3,}/g, '\n\n').replace(/[ \t]+$/gm, '').replace(/\n*$/, '\n')
}

function isUnsupported(b: HookBinding | HookUnsupported): b is HookUnsupported {
  return typeof (b as HookUnsupported).unsupported === 'string'
}

function matcherText(m: HookBinding['matcher']): string | undefined {
  if (m === undefined) return undefined
  if (typeof m === 'string') return m
  if (Array.isArray(m)) return m.map(String).join(' | ')
  return JSON.stringify(m)
}

const BLOCKING_TEXT: Record<HookSpec['blocking'], string> = {
  none: 'no',
  deny: 'yes: it can deny a tool call',
  stop: 'yes: it can keep a turn from ending',
}
const FAILURE_TEXT: Record<HookSpec['failure'], string> = {
  open: 'the call goes through (fail-open)',
  closed: 'the call is denied (fail-closed)',
}

function bindingSummary(b: HookBinding | HookUnsupported | undefined): string {
  if (b === undefined || b === null || typeof b !== 'object') return '—'
  if (isUnsupported(b)) return 'unsupported'
  const parts = [code(String(b.event ?? '?'))]
  const m = matcherText(b.matcher)
  if (m !== undefined) parts.push(code(m))
  if (b.async === true) parts.push('async')
  return parts.join(' · ')
}

function normalizeHook(raw: unknown): HookSpec {
  const h = (raw !== null && typeof raw === 'object' ? raw : {}) as Record<string, unknown>
  const bindings = (h['bindings'] !== null && typeof h['bindings'] === 'object' ? h['bindings'] : {}) as HookSpec['bindings']
  const spec = {
    id: String(h['id'] ?? '?'),
    name: String(h['name'] ?? '?'),
    blocking: String(h['blocking'] ?? 'none'),
    failure: String(h['failure'] ?? 'open'),
    bindings,
    contract_test: typeof h['contract_test'] === 'string' ? h['contract_test'] : '',
  } as HookSpec
  if (typeof h['description'] === 'string') spec.description = h['description']
  return spec
}

function hooksDoc(c: CanonicalBundle): string {
  let out = banner('`canonical/hooks.yaml`')
  out += '# Hook matrix\n\n'
  out += 'Buracle\'s logical hooks and what each one is bound to on every harness. The hook logic is written once in `src/core`; each adapter binds every hook to the events below.\n\n'
  out += '- **Blocks?** `none`: it only adds context or records something. `deny`: it can deny a tool call. `stop`: it can keep a turn from ending.\n'
  out += '- **On failure:** what happens when the hook itself crashes. `open`: the call goes through. `closed`: the call is denied.\n'
  out += '- **Mode:** the harness waits for a sync hook; an async hook runs in the background and nothing waits for its result.\n'
  out += '- **(also):** a further event the same hook listens to on that harness.\n'
  out += '- **Claude:** `classic.<Event>` is a command hook in the plugin\'s `hooks/hooks.json` (`buracle hook claude <Event>`). The command hooks are the backbone and run everywhere: the terminal, VS Code, the desktop app and `-p`. The other Claude events (such as `tool.call`, `command.run` and `session.measure`) belong to the mod (`hooks/register.tsx`), which only adds what a mod alone can do and lets the call through when it fails.\n\n'
  const hooks = c.hooks.hooks.map(normalizeHook).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
  if (hooks.length === 0) {
    out += '> `canonical/hooks.yaml` defines no hooks yet; there is nothing to list.\n'
    return finish(out)
  }
  out += '## Summary\n\n'
  out += mdTable(
    ['ID', 'Name', 'Blocks?', 'On failure', ...HARNESSES.map(h => HARNESS_LABEL[h])],
    hooks.map(h => [h.id, code(h.name), code(h.blocking), code(h.failure), ...HARNESSES.map(x => bindingSummary(h.bindings[x]))]),
  )
  out += '\n`unsupported`: the harness has no equivalent (the reason is in the details).\n\n'
  out += '## Details\n\n'
  for (const h of hooks) {
    out += `### ${h.id} \`${h.name}\`\n\n`
    if (typeof h.description === 'string' && h.description.trim() !== '') out += `${h.description.trim()}\n\n`
    out += `- Blocks? ${BLOCKING_TEXT[h.blocking] ?? h.blocking}\n`
    out += `- If the hook fails: ${FAILURE_TEXT[h.failure] ?? h.failure}\n`
    if (typeof h.contract_test === 'string' && h.contract_test !== '') out += `- Contract test: \`${h.contract_test}\`\n`
    out += '\n'
    const rows: string[][] = []
    for (const x of HARNESSES) {
      const b = h.bindings[x]
      if (b === undefined || b === null || typeof b !== 'object') { rows.push([HARNESS_LABEL[x], '—', '—', '—', '—']); continue }
      if (isUnsupported(b)) { rows.push([HARNESS_LABEL[x], `unsupported: ${cell(b.unsupported)}`, '—', '—', '—']); continue }
      const row = (label: string, e: { event?: unknown, matcher?: HookBinding['matcher'], async?: boolean, timeoutMs?: number }): string[] => [
        label,
        code(String(e.event ?? '?')),
        matcherText(e.matcher) !== undefined ? code(matcherText(e.matcher) as string) : '—',
        e.async === true ? 'async' : 'sync',
        typeof e.timeoutMs === 'number' ? `${e.timeoutMs} ms` : '—',
      ]
      rows.push(row(HARNESS_LABEL[x], b))
      for (const a of Array.isArray(b.also) ? b.also : []) rows.push(row(`${HARNESS_LABEL[x]} (also)`, a))
      for (const f of hookFallbacks(b)) rows.push(row(`${HARNESS_LABEL[x]} (classic fallback)`, f))
    }
    out += mdTable(['Harness', 'Event', 'Matcher', 'Mode', 'Timeout'], rows)
    out += '\n'
  }
  return finish(out)
}

const EXIT_TEXT: Record<string, string> = {
  ok: 'success',
  error: 'error',
  partial: 'partial success, or the user needs to act',
}

function cliDoc(commands: readonly CommandInfo[], exitCodes: Readonly<Record<string, number>>): string {
  let out = banner('the CLI command registry (`src/cli/router.ts`)')
  out += '# `buracle` command reference\n\n'
  out += 'The summary and usage text of every command come straight from the command itself, so they are exactly what the CLI prints.\n\n'
  out += '## Global flags\n\n'
  out += '- `--json`: machine-readable output\n- `--verbose`: more detail on stderr\n- `--help`: help (`buracle <command> --help` for one command)\n- `--version`: the Buracle version\n\n'
  out += '## Exit codes\n\n'
  out += mdTable(['Code', 'Meaning'], Object.entries(exitCodes).sort((a, b) => a[1] - b[1]).map(([k, v]) => [code(String(v)), cell(EXIT_TEXT[k] ?? k)]))
  out += '\n## Commands\n\n'
  out += mdTable(['Command', 'Summary'], commands.map(c => [`[\`${c.name}\`](#buracle-${c.name})`, prose(c.summary)]))
  out += '\n'
  for (const c of commands) {
    out += `## buracle ${c.name}\n\n`
    out += `${prose(c.summary)}\n\n`
    out += '```text\n' + c.usage.replace(/\s+$/, '') + '\n```\n\n'
  }
  return finish(out)
}

