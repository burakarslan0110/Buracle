export function configDescription(key: string): string | undefined {
  const h = HARNESS_ENABLED.exec(key)
  if (h && h[1] !== undefined) {
    const label = (HARNESS_LABEL as Record<string, string>)[h[1]] ?? h[1]
    return `Turns ${label} support on or off. A disabled harness gets nothing installed: \`buracle install\` skips it.`
  }
  return CONFIG_DESCRIPTIONS[key]
}

function isPlainObject(x: unknown): x is Record<string, unknown> {
  return x !== null && typeof x === 'object' && !Array.isArray(x)
}

export function configLeaves(value: unknown, prefix = ''): Array<{ key: string, value: unknown }> {
  if (!isPlainObject(value)) return [{ key: prefix, value }]
  const out: Array<{ key: string, value: unknown }> = []
  for (const k of Object.keys(value)) out.push(...configLeaves(value[k], prefix === '' ? k : `${prefix}.${k}`))
  return out
}

function cloneJson<T>(x: T): T {
  return JSON.parse(JSON.stringify(x)) as T
}

